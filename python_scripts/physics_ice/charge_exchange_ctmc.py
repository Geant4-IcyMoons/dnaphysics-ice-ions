@lru_cache(maxsize=512)
def projectile_velocity_au(energy_keV_u: float) -> float:
    energy_ha_per_u = float(energy_keV_u) * KEV_TO_HARTREE
    return math.sqrt(2.0 * energy_ha_per_u / U_TO_ELECTRON_MASS)


def paper_minimum_integration_time_au(energy_keV_u: float) -> float:
    """Published lower bound for the trajectory integration interval.

    Liamsuwan and Nikjoo define 1--25 keV/u as the low-energy region and state
    that low- and intermediate-energy trajectories were integrated for at
    least 10^4 and 10^3 atomic time units, respectively.
    """
    return 1.0e4 if float(energy_keV_u) <= 25.0 else 1.0e3


@lru_cache(maxsize=16)
def _trajectory_cores(
    charge_state: int, bound_to: str
) -> tuple[CorePotential, CorePotential]:
    """Build the two invariant screened cores once per worker and channel."""
    q = int(charge_state)
    if bound_to == "target":
        return (
            CorePotential.from_zn(WATER_PSEUDO_NUCLEAR_CHARGE, 9),
            CorePotential.from_zn(
                PROJECTILE_NUCLEAR_CHARGE, PROJECTILE_NUCLEAR_CHARGE - q
            ),
        )
    if bound_to == "projectile":
        if q not in PROJECTILE_OUTER_ORBITAL:
            raise ValueError(
                f"{PROJECTILE.symbol}{q}+ has no projectile electron to lose"
            )
        return (
            CorePotential.from_zn(WATER_PSEUDO_NUCLEAR_CHARGE, 10),
            CorePotential.from_zn(
                PROJECTILE_NUCLEAR_CHARGE,
                PROJECTILE_NUCLEAR_CHARGE - q - 1,
            ),
        )
    raise ValueError("bound_to must be 'target' or 'projectile'")


def _electron_core_energy_relative(
    relative: np.ndarray,
    core_index: int,
    core: CorePotential,
    core_mass_au: float,
    minimum_radius_au: float,
) -> float:
    """Electron energy relative to the reference (0) or other (1) core."""
    if core_index == 0:
        relative_position = relative[3:6]
        relative_velocity = relative[9:12]
    elif core_index == 1:
        relative_position = relative[3:6] - relative[:3]
        relative_velocity = relative[9:12] - relative[6:9]
    else:
        raise ValueError("core_index must be 0 (target) or 1 (projectile)")
    radius = max(float(np.linalg.norm(relative_position)), minimum_radius_au)
    reduced_mass = (
        ELECTRON_MASS_AU
        * core_mass_au
        / (ELECTRON_MASS_AU + core_mass_au)
    )
    return float(
        0.5 * reduced_mass * np.dot(relative_velocity, relative_velocity)
        - potential_magnitude(core, radius)
    )


def _build_initial_relative_state(
    *,
    energy_keV_u: float,
    impact_parameter_au: float,
    separation_au: float,
    bound_to: str,
    binding_eV: float,
    target_core: CorePotential,
    projectile_core: CorePotential,
    radial_grid_points: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """Build the paper's 12 scheme-specific relative variables."""
    velocity = projectile_velocity_au(energy_keV_u)
    target_position = np.zeros(3, dtype=float)
    target_velocity = np.zeros(3, dtype=float)
    projectile_center_position = np.array(
        [impact_parameter_au, 0.0, -separation_au],
        dtype=float,
    )
    projectile_center_velocity = np.array(
        [0.0, 0.0, velocity],
        dtype=float,
    )
    origin = np.zeros(3, dtype=float)

    if bound_to == "target":
        electron_offset, electron_relative_velocity = sample_bound_electron(
            target_core,
            WATER_MASS_AU,
            binding_eV,
            origin,
            origin,
            radial_grid_points,
            rng,
        )
        target_fraction = ELECTRON_MASS_AU / (
            WATER_MASS_AU + ELECTRON_MASS_AU
        )
        target_position = -target_fraction * electron_offset
        target_velocity = -target_fraction * electron_relative_velocity
        projectile_position = projectile_center_position
        projectile_velocity = projectile_center_velocity
        electron_position = target_position + electron_offset
        electron_velocity = target_velocity + electron_relative_velocity
    elif bound_to == "projectile":
        electron_offset, electron_relative_velocity = sample_bound_electron(
            projectile_core,
            PROJECTILE_MASS_AU,
            binding_eV,
            origin,
            origin,
            radial_grid_points,
            rng,
        )
        projectile_fraction = ELECTRON_MASS_AU / (
            PROJECTILE_MASS_AU + ELECTRON_MASS_AU
        )
        projectile_position = (
            projectile_center_position
            - projectile_fraction * electron_offset
        )
        projectile_velocity = (
            projectile_center_velocity
            - projectile_fraction * electron_relative_velocity
        )
        electron_position = projectile_position + electron_offset
        electron_velocity = (
            projectile_velocity + electron_relative_velocity
        )
    else:
        raise ValueError("bound_to must be 'target' or 'projectile'")

    relative = np.empty(12, dtype=float)
    if bound_to == "target":
        relative[:3] = projectile_position - target_position
        relative[3:6] = electron_position - target_position
        relative[6:9] = projectile_velocity - target_velocity
        relative[9:12] = electron_velocity - target_velocity
    else:
        # Paper Appendix A: switch p and t in the projectile-loss scheme.
        # Keeping the bound electron relative to its projectile core also
        # avoids subtracting two coordinates displaced by up to 20,000 a.u.
        relative[:3] = target_position - projectile_position
        relative[3:6] = electron_offset
        relative[6:9] = target_velocity - projectile_velocity
        relative[9:12] = electron_relative_velocity
    return relative


def _cores_are_separated_and_receding(
    state: np.ndarray,
    initial_core_distance: float,
) -> bool:
    """Return whether the nuclei are back outside the initial boundary."""
    positions = state[:9].reshape(3, 3)
    velocities = state[9:].reshape(3, 3)
    displacement = positions[1] - positions[0]
    relative_velocity = velocities[1] - velocities[0]
    return bool(
        np.linalg.norm(displacement) >= initial_core_distance
        and np.dot(displacement, relative_velocity) > 0.0
    )


def _integrate_scipy_until_separated(
    *,
    initial_state: np.ndarray,
    minimum_integration_time_au: float,
    target_core: CorePotential,
    projectile_core: CorePotential,
    minimum_radius_au: float,
    rtol: float,
    atol: float,
    max_step: float,
) -> np.ndarray | None:
    """SciPy reference integration with the paper's exit condition."""
    positions = initial_state[:9].reshape(3, 3)
    velocities = initial_state[9:].reshape(3, 3)
    initial_displacement = positions[1] - positions[0]
    initial_core_distance = float(np.linalg.norm(initial_displacement))
    initial_relative_speed = float(
        np.linalg.norm(velocities[1] - velocities[0])
    )
    state = initial_state.copy()
    elapsed = 0.0
    solver_args = (target_core, projectile_core, minimum_radius_au)

    if minimum_integration_time_au > 0.0:
        solution = solve_ivp(
            _three_body_rhs,
            (0.0, minimum_integration_time_au),
            state,
            method="DOP853",
            t_eval=(minimum_integration_time_au,),
            args=solver_args,
            rtol=rtol,
            atol=atol,
            max_step=max_step,
        )
        if not solution.success or solution.y.shape[1] == 0:
            return None
        state = solution.y[:, -1]
        elapsed = minimum_integration_time_au

    if _cores_are_separated_and_receding(state, initial_core_distance):
        return state

    # This is only a solver restart interval; it is not a physical boundary.
    # The physical stop is the outward crossing of the published initial
    # separation.  One initial-separation flight time avoids tiny segments.
    continuation_interval = initial_core_distance / max(
        initial_relative_speed,
        np.finfo(float).tiny,
    )

    def outward_initial_boundary(
        _: float,
        candidate: np.ndarray,
        *__: object,
    ) -> float:
        candidate_positions = candidate[:9].reshape(3, 3)
        displacement = candidate_positions[1] - candidate_positions[0]
        return float(np.linalg.norm(displacement) - initial_core_distance)

    outward_initial_boundary.terminal = True
    outward_initial_boundary.direction = 1.0

    while True:
        interval_end = elapsed + continuation_interval
        solution = solve_ivp(
            _three_body_rhs,
            (elapsed, interval_end),
            state,
            method="DOP853",
            args=solver_args,
            rtol=rtol,
            atol=atol,
            max_step=max_step,
            events=outward_initial_boundary,
        )
        if not solution.success or solution.y.shape[1] == 0:
            return None
        if solution.y_events and solution.y_events[0].shape[0] > 0:
            return np.asarray(solution.y_events[0][-1], dtype=float)
        state = solution.y[:, -1]
        elapsed = interval_end


def simulate_one_trajectory(
    *,
    energy_keV_u: float,
    charge_state: int,
    impact_parameter_au: float,
    bound_to: str,
    binding_eV: float,
    start_separation_au: float,
    minimum_integration_time_au: float,
    config: CTMCConfig,
    rng: np.random.Generator,
) -> tuple[str, bool, float]:
    """
    Return (outcome, success, relative total-energy drift).

    Outcomes are "ionized", "captured_projectile", "retained_target", and
    "ambiguous_bound". In the target-electron scheme, capture means the
    physically required E_ep <= 0 and E_et > 0. The inequality printed for
    capture in the paper's prose is reversed relative to the definitions of
    E_et and E_ep and would classify an electron retained by H2O as captured.
    """
    q = int(charge_state)
    if bound_to == "projectile" and q not in PROJECTILE_OUTER_ORBITAL:
        return "retained_target", True, 0.0
    target_core, projectile_core = _trajectory_cores(q, bound_to)
    if bound_to == "target":
        reference_core = target_core
        other_core = projectile_core
        reference_mass = WATER_MASS_AU
        other_mass = PROJECTILE_MASS_AU
    else:
        # Appendix A switches p and t for the projectile-loss equations.
        reference_core = projectile_core
        other_core = target_core
        reference_mass = PROJECTILE_MASS_AU
        other_mass = WATER_MASS_AU

    # A boundary-convergence retry must preserve the sampled microcanonical
    # phase and consume exactly four random draws, just like every other
    # trajectory. Rewinding before each larger-boundary attempt achieves both.
    initial_rng_state = rng.bit_generator.state
    separation = float(start_separation_au)
    while True:
        initial_relative = _build_initial_relative_state(
            energy_keV_u=energy_keV_u,
            impact_parameter_au=impact_parameter_au,
            separation_au=separation,
            bound_to=bound_to,
            binding_eV=binding_eV,
            target_core=target_core,
            projectile_core=projectile_core,
            radial_grid_points=config.radial_grid_points,
            rng=rng,
        )
        initial_energy = relative_three_body_energy(
            initial_relative,
            target_core,
            projectile_core,
            config.minimum_radius_au,
            bound_to,
        )

        final_relative: np.ndarray | None = None
        final_energy_drift = math.inf
        had_finite_endpoint = False
        tolerance_pairs = (
            (config.rtol, config.atol),
            (config.retry_rtol, config.retry_atol),
            (0.1 * config.retry_rtol, 0.1 * config.retry_atol),
        )
        for integration_rtol, integration_atol in tolerance_pairs:
            candidate: np.ndarray | None = None
            if config.backend == "numba":
                if integrate_relative_dop853 is None:
                    raise RuntimeError(
                        "The Numba backend was requested but could not be "
                        "imported"
                    ) from _NUMBA_IMPORT_ERROR
                success, candidate, _, _ = integrate_relative_dop853(
                    initial_relative,
                    minimum_integration_time_au,
                    _cached_core_parameters(reference_core),
                    _cached_core_parameters(other_core),
                    integration_rtol,
                    integration_atol,
                    config.max_step_au,
                    config.minimum_radius_au,
                    reference_mass,
                    other_mass,
                    config.maximum_integration_steps,
                )
                if not success:
                    candidate = None
            elif config.backend == "scipy":
                initial_state = _relative_to_state(
                    initial_relative,
                    bound_to,
                )
                max_step = (
                    np.inf
                    if not np.isfinite(config.max_step_au)
                    else config.max_step_au
                )
                final_state = _integrate_scipy_until_separated(
                    initial_state=initial_state,
                    minimum_integration_time_au=minimum_integration_time_au,
                    target_core=target_core,
                    projectile_core=projectile_core,
                    minimum_radius_au=config.minimum_radius_au,
                    rtol=integration_rtol,
                    atol=integration_atol,
                    max_step=max_step,
                )
                if final_state is not None and np.all(
                    np.isfinite(final_state)
                ):
                    candidate = _state_to_relative_coordinates(
                        final_state,
                        bound_to,
                    )
            else:  # Defensive: CLI validation should make this unreachable.
                raise ValueError(
                    f"Unknown CTMC backend: {config.backend!r}"
                )

            if candidate is None or not np.all(np.isfinite(candidate)):
                continue
            candidate_energy = relative_three_body_energy(
                candidate,
                target_core,
                projectile_core,
                config.minimum_radius_au,
                bound_to,
            )
            candidate_drift = abs(candidate_energy - initial_energy) / max(
                abs(initial_energy), 1.0
            )
            had_finite_endpoint = True
            if candidate_drift <= final_energy_drift:
                final_relative = candidate
                final_energy_drift = float(candidate_drift)
            if candidate_drift <= config.maximum_relative_energy_drift:
                break

        needs_regularized_retry = (
            final_relative is None
            or final_energy_drift
            > config.maximum_relative_energy_drift
        )
        if (
            needs_regularized_retry
            and config.backend == "numba"
            and integrate_relative_dop853_regularized is not None
        ):
            # Exceptionally eccentric microcanonical phases can drive an
            # electron arbitrarily close to a Coulombic core. If every
            # physical-time endpoint is absent or fails the independent
            # energy-conservation check, retry the identical trajectory in a
            # positive Sundman time parameter. This changes only numerical
            # parameterization, not the paper's Newtonian equations,
            # potentials, initial state, acceptance limit, or endpoint.
            for integration_rtol, integration_atol in tolerance_pairs:
                success, candidate, _, _ = (
                    integrate_relative_dop853_regularized(
                        initial_relative,
                        minimum_integration_time_au,
                        _cached_core_parameters(reference_core),
                        _cached_core_parameters(other_core),
                        integration_rtol,
                        integration_atol,
                        config.max_step_au,
                        config.minimum_radius_au,
                        reference_mass,
                        other_mass,
                        config.maximum_relative_energy_drift,
                        config.maximum_integration_steps,
                    )
                )
                if not success or not np.all(np.isfinite(candidate)):
                    continue
                candidate_energy = relative_three_body_energy(
                    candidate,
                    target_core,
                    projectile_core,
                    config.minimum_radius_au,
                    bound_to,
                )
                candidate_drift = abs(
                    candidate_energy - initial_energy
                ) / max(abs(initial_energy), 1.0)
                had_finite_endpoint = True
                if candidate_drift <= final_energy_drift:
                    final_relative = candidate
                    final_energy_drift = float(candidate_drift)
                if (
                    candidate_drift
                    <= config.maximum_relative_energy_drift
                ):
                    break

        if not had_finite_endpoint:
            return "integration_failure", False, math.inf
        if (
            final_relative is None
            or final_energy_drift > config.maximum_relative_energy_drift
        ):
            return "energy_conservation_failure", False, final_energy_drift
        energy_drift = final_energy_drift

        if bound_to == "target":
            energy_target = _electron_core_energy_relative(
                final_relative,
                0,
                target_core,
                WATER_MASS_AU,
                config.minimum_radius_au,
            )
            energy_projectile = _electron_core_energy_relative(
                final_relative,
                1,
                projectile_core,
                PROJECTILE_MASS_AU,
                config.minimum_radius_au,
            )
        else:
            energy_projectile = _electron_core_energy_relative(
                final_relative,
                0,
                projectile_core,
                PROJECTILE_MASS_AU,
                config.minimum_radius_au,
            )
            energy_target = _electron_core_energy_relative(
                final_relative,
                1,
                target_core,
                WATER_MASS_AU,
                config.minimum_radius_au,
            )

        if energy_target > 0.0 and energy_projectile > 0.0:
            return "ionized", True, float(energy_drift)
        if energy_projectile <= 0.0 and energy_target > 0.0:
            return "captured_projectile", True, float(energy_drift)
        if energy_target <= 0.0 and energy_projectile > 0.0:
            return "retained_target", True, float(energy_drift)

        # E_et <= 0 and E_ep <= 0 is the paper's non-physical final state.
        # Apply its prescribed remedy by increasing z0 and integrating the
        # identical sampled phase for the correspondingly longer interval.
        separation *= config.boundary_extension_factor
        if not math.isfinite(separation):
            return "ambiguous_bound", False, float(energy_drift)
        rng.bit_generator.state = initial_rng_state


