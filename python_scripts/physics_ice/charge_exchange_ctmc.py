@dataclass(frozen=True)
class CorePotential:
    nuclear_charge: int
    spectators: int
    eta: float
    zeta: float

    @classmethod
    def from_zn(cls, nuclear_charge: int, spectators: int) -> "CorePotential":
        try:
            p = SCREENING_BY_SPECTATORS[int(spectators)]
        except KeyError as exc:
            raise ValueError(
                f"No Garvey screening parameters for N={spectators}"
            ) from exc
        charge_offset = nuclear_charge - spectators - 1
        eta = p.eta0 + p.eta1 * charge_offset
        zeta = p.zeta0 + p.zeta1 * charge_offset
        if spectators == 0:
            # eta and zeta do not affect an unscreened core, but finite values
            # keep the generic implementation numerically well defined.
            eta = 0.0
            zeta = 1.0
        if zeta <= 0.0:
            raise ValueError(
                f"Non-positive Garvey zeta for Z={nuclear_charge}, N={spectators}"
            )
        return cls(
            nuclear_charge=int(nuclear_charge),
            spectators=int(spectators),
            eta=float(eta),
            zeta=float(zeta),
        )


