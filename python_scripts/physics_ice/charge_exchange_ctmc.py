def parse_float_list(text: str) -> np.ndarray:
    values = [
        float(item.strip())
        for item in text.replace(";", ",").split(",")
        if item.strip()
    ]
    if not values:
        raise argparse.ArgumentTypeError("Expected at least one numeric value")
    values = sorted(set(values))
    if values[0] <= 0.0:
        raise argparse.ArgumentTypeError("Energies must be positive")
    return np.asarray(values, dtype=float)


def parse_per_energy_values(
    text: str | None,
    energies: np.ndarray,
    option_name: str,
) -> tuple[float, ...]:
    """Parse one explicitly supplied value for every selected energy."""
    if text is None:
        raise ValueError(
            f"{option_name} is required because the paper does not publish "
            "the intermediate per-energy values"
        )
    values = tuple(
        float(item.strip())
        for item in text.replace(";", ",").split(",")
        if item.strip()
    )
    if len(values) != energies.size:
        raise ValueError(
            f"{option_name} requires exactly {energies.size} comma-separated "
            "values in the same order as the selected energies"
        )
    if any(not math.isfinite(value) or value <= 0.0 for value in values):
        raise ValueError(f"All {option_name} values must be finite and positive")
    return values


def resolve_paper_trajectory_boundaries(
    args: argparse.Namespace,
    energies: np.ndarray,
) -> tuple[tuple[float, ...], tuple[float, ...]]:
    """Validate published boundary facts without inventing interpolation."""
    separations = parse_per_energy_values(
        args.start_separation_au,
        energies,
        "--start-separation-au",
    )
    if any(value < 1.0e3 for value in separations):
        raise ValueError(
            "--start-separation-au values must be at least the paper's "
            "published 10^3 a.u. lower endpoint"
        )
    for energy, separation in zip(energies, separations, strict=True):
        if math.isclose(float(energy), 1.0) and separation < 1.0e4:
            raise ValueError(
                "The paper specifies at least 10^4 a.u. initial separation "
                "at 1 keV/u"
            )
        if math.isclose(float(energy), 1.0e4) and separation < 1.0e3:
            raise ValueError(
                "The paper specifies at least 10^3 a.u. initial separation at "
                "10 MeV/u"
            )

    published_minima = tuple(
        paper_minimum_integration_time_au(float(energy))
        for energy in energies
    )
    if args.minimum_integration_time_au is None:
        minimum_times = published_minima
    else:
        minimum_times = parse_per_energy_values(
            args.minimum_integration_time_au,
            energies,
            "--minimum-integration-time-au",
        )
        for energy, value, published_minimum in zip(
            energies,
            minimum_times,
            published_minima,
            strict=True,
        ):
            if value < published_minimum:
                raise ValueError(
                    "--minimum-integration-time-au is shorter than the "
                    f"paper's lower bound at E={energy:g} keV/u "
                    f"({published_minimum:g} a.u.)"
                )
    return separations, minimum_times


def parse_charges(
    text: str,
    charge_step: int,
    maximum_charge: int | None = None,
) -> np.ndarray:
    cleaned = text.strip()
    if ":" in cleaned:
        parts = [part.strip() for part in cleaned.split(":")]
        if len(parts) != 2:
            raise ValueError("Charge range must have form qmin:qmax")
        qmin, qmax = map(int, parts)
        charges = np.arange(qmin, qmax + 1, charge_step, dtype=int)
    else:
        charges = np.asarray(
            sorted(set(int(part.strip()) for part in cleaned.split(",") if part.strip())),
            dtype=int,
        )
    if charges.size == 0:
        raise ValueError("No charge states selected")
    qmax = (
        PROJECTILE_NUCLEAR_CHARGE
        if maximum_charge is None
        else int(maximum_charge)
    )
    if np.any((charges < 0) | (charges > qmax)):
        raise ValueError(
            f"{PROJECTILE.name.capitalize()} charge states must lie in "
            f"0,...,{qmax}"
        )
    return charges


def build_energy_grid(args: argparse.Namespace) -> np.ndarray:
    if args.energies is not None:
        return parse_float_list(args.energies)
    if args.energy_step_kev_u is not None:
        step = float(args.energy_step_kev_u)
        if step <= 0.0:
            raise ValueError("--energy-step-kev-u must be positive")
        count = int(
            math.floor(
                (args.energy_max_kev_u - args.energy_min_kev_u) / step
            )
        )
        grid = args.energy_min_kev_u + step * np.arange(count + 1)
        if grid[-1] < args.energy_max_kev_u * (1.0 - 1.0e-12):
            grid = np.append(grid, args.energy_max_kev_u)
        return np.asarray(grid, dtype=float)
    if (
        PROJECTILE.default_energy_grid_kev_u is not None
        and math.isclose(
            args.energy_min_kev_u,
            PROJECTILE.default_energy_min_kev_u,
        )
        and math.isclose(
            args.energy_max_kev_u,
            PROJECTILE.default_energy_max_kev_u,
        )
        and args.energy_points == PROJECTILE.default_energy_points
        and args.energy_spacing == PROJECTILE.default_energy_spacing
    ):
        return np.asarray(
            PROJECTILE.default_energy_grid_kev_u,
            dtype=float,
        )
    if args.energy_points < 2:
        raise ValueError("--energy-points must be at least two")
    if args.energy_spacing == "linear":
        return np.linspace(
            args.energy_min_kev_u,
            args.energy_max_kev_u,
            args.energy_points,
        )
    return np.geomspace(
        args.energy_min_kev_u,
        args.energy_max_kev_u,
        args.energy_points,
    )


def configuration_signature(
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    config: CTMCConfig,
) -> str:
    config_payload = asdict(config)
    projectile_key = str(config_payload.pop("projectile", "carbon"))
    # Scheduling granularity does not alter trajectory streams or physics and
    # may be tuned safely when resuming.
    config_payload.pop("trajectory_chunk_size", None)
    if not np.isfinite(config_payload["max_step_au"]):
        config_payload["max_step_au"] = None
    payload = {
        "energies": energies.tolist(),
        "charges": charges.tolist(),
        "impact_au": impact_au.tolist(),
        "config": config_payload,
        "model_version": 9,
    }
    # Preserve the exact legacy carbon signature so all live carbon shards can
    # continue from checkpoints created before the shared-engine refactor.
    if projectile_key != "carbon":
        projectile = PROJECTILES[projectile_key]
        payload["projectile"] = {
            "key": projectile.key,
            "nuclear_charge": projectile.nuclear_charge,
            "mass_au": projectile.mass_au,
            "outer_orbitals": {
                str(charge): asdict(orbital)
                for charge, orbital in projectile.outer_orbitals.items()
            },
            "screening_by_spectators": {
                str(spectators): asdict(
                    SCREENING_BY_SPECTATORS[spectators]
                )
                for spectators in range(projectile.nuclear_charge + 1)
            },
        }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(encoded).hexdigest()


