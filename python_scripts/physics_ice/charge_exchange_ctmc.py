def h2o_number_density_cm3(mass_density_g_cm3: float) -> float:
    """Convert bulk H2O mass density to molecular number density."""
    density = float(mass_density_g_cm3)
    if not np.isfinite(density) or density <= 0.0:
        raise ValueError("H2O mass density must be finite and positive")
    return density * AVOGADRO / H2O_MOLAR_MASS_G_MOL


