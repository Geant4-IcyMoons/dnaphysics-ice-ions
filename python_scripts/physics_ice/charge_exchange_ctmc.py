    global PROJECTILE
    global PROJECTILE_MASS_AU
    global PROJECTILE_NUCLEAR_CHARGE
    global PROJECTILE_OUTER_ORBITAL
    changed = projectile.key != PROJECTILE.key
    PROJECTILE = projectile
    PROJECTILE_MASS_AU = projectile.mass_au
    PROJECTILE_NUCLEAR_CHARGE = projectile.nuclear_charge
    PROJECTILE_OUTER_ORBITAL = projectile.outer_orbitals
    if changed:
        cached_cores = globals().get("_trajectory_cores")
        if cached_cores is not None:
            cached_cores.cache_clear()
    return projectile


