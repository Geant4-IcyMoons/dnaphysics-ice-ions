#!/usr/bin/env python3
"""
Shared C(q+)/Li(q+)/O(q+)/S(q+) + H2O charge-changing CTMC engine for Geant4.

Physics basis
-------------
This is an independent-water-molecule, three-body CTMC implementation of the
framework in:

    T. Liamsuwan and H. Nikjoo, Phys. Med. Biol. 58 (2013) 641-672
    https://doi.org/10.1088/0031-9155/58/3/641

The lithium charge states, adjacent transitions, and first ten energy points
follow:

    N. D-Kondo et al., Phys. Med. Biol. 69 (2024) 145016
    https://doi.org/10.1088/1361-6560/ad5f72

Lithium adds one explicitly identified CTMC endpoint at 100 MeV total Li-7
energy, outside the paper's 70 MeV total-energy range.

The code implements:

* the Garvey screened-core potential (paper equations 6-9);
* microcanonical initial electron sampling (equations 3-5);
* the paper's 12 relative-coordinate equations with a Numba-compiled
  adaptive DOP853 integrator (SciPy DOP853 remains as a reference backend);
* the modified IEVM and IPM channel construction (equations 13-19);
* impact-parameter integration (equation 20).

The generated microscopic cross sections are per H2O molecule. Ice density is
therefore NOT applied here. Geant4 must form the macroscopic cross section as

    Sigma(E, q) = n_H2O * sigma(E, q).

Important terminology
---------------------
The q used here is the discrete projectile charge state: q=0,...,6 for
carbon, q=0,...,3 for lithium, q=0,...,8 for oxygen, and q=0,...,16 for
sulfur. It is not the momentum-transfer variable used in dielectric/ELF
integrations. Hence dq=1 physically. Charge exchange is not generated by a
dE dq ELF integral.

Outputs
-------
<element>_charge_exchange_h2o.dat
    Geant4-oriented text table:
    E_keV_u q SC TI SL LI decrease increase  [cross sections in cm2/H2O]

<element>_charge_exchange_h2o.csv
    The same table with named CSV columns.

<element>_charge_exchange_probabilities.npz
    One-electron probabilities on the impact-parameter grid, useful for
    convergence checks and restart.

<element>_charge_exchange_metadata.json
    Full numerical configuration and provenance.

The publication settings used by the paper are expensive: more than 10,000
trajectories for every impact parameter. Use small --trajectories and
--impact-points only for software smoke tests, never for production physics.
The scheduler splits each physical channel into deterministic trajectory
chunks, evaluates longer low-energy work first, keeps only a bounded number of
futures in memory, and checkpoints raw partial-channel counts. Parent-owned
tqdm bars report both attempted trajectories and completed grid points without
a contended multiprocessing lock. Stable node shards support multi-node runs
through a shared filesystem. These optimizations do not reduce the requested
Monte Carlo statistics.
"""

