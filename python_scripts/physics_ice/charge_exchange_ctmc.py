def validate_args(args: argparse.Namespace) -> None:
    if args.energy_min_kev_u <= 0.0:
        raise ValueError("--energy-min-kev-u must be positive")
    if args.energy_max_kev_u <= args.energy_min_kev_u:
        raise ValueError("--energy-max-kev-u must exceed the minimum")
    if args.charge_step < 1:
        raise ValueError("--charge-step must be a positive integer")
    if args.impact_points < 2:
        raise ValueError("--impact-points must be at least two")
    if args.trajectories < 1:
        raise ValueError("--trajectories must be positive")
    if args.workers < 0:
        raise ValueError("--workers must be non-negative (0 means auto)")
    if args.trajectory_chunk_size < 1:
        raise ValueError("--trajectory-chunk-size must be positive")
    if args.trajectory_chunk_size > args.trajectories:
        args.trajectory_chunk_size = args.trajectories
    if args.pending_factor < 1:
        raise ValueError("--pending-factor must be positive")
    if args.start_method != "auto":
        if args.start_method not in multiprocessing.get_all_start_methods():
            raise ValueError(
                f"Multiprocessing start method {args.start_method!r} "
                "is not available on this platform"
            )
    if args.backend == "numba" and integrate_relative_dop853 is None:
        raise ValueError(
            "The Numba backend is unavailable: "
            f"{_NUMBA_IMPORT_ERROR!s}. Use --backend scipy or install numba."
        )
    if args.maximum_integration_steps < 0:
        raise ValueError(
            "--maximum-integration-steps must be non-negative (0 disables it)"
        )
    if args.radial_grid_points < 128:
        raise ValueError("--radial-grid-points must be at least 128")
    if (
        args.rtol <= 0.0
        or args.atol <= 0.0
        or args.retry_rtol <= 0.0
        or args.retry_atol <= 0.0
    ):
        raise ValueError("Integrator tolerances must be positive")
    if args.retry_rtol >= args.rtol or args.retry_atol >= args.atol:
        raise ValueError(
            "Retry tolerances must be smaller than the primary tolerances"
        )
    if (
        not math.isfinite(args.boundary_extension_factor)
        or args.boundary_extension_factor <= 1.0
    ):
        raise ValueError("--boundary-extension-factor must exceed one")
    if args.minimum_radius_au <= 0.0:
        raise ValueError("--minimum-radius-au must be positive")
    if (
        not math.isfinite(args.maximum_relative_energy_drift)
        or args.maximum_relative_energy_drift <= 0.0
    ):
        raise ValueError(
            "--maximum-relative-energy-drift must be finite and positive"
        )
    if not (0.0 <= args.max_failure_fraction < 1.0):
        raise ValueError("--max-failure-fraction must lie in [0,1)")
    if args.checkpoint_every < 1:
        raise ValueError("--checkpoint-every must be positive")
    if args.checkpoint_seconds < 0.0:
        raise ValueError("--checkpoint-seconds must be non-negative")
    if args.seed < 0:
        raise ValueError("--seed must be non-negative")
    if args.shard_count < 1:
        raise ValueError("--shard-count must be positive")
    if not (0 <= args.shard_index < args.shard_count):
        raise ValueError("--shard-index must lie in [0, shard-count)")
    if args.merge_shards and args.shard_count < 2:
        raise ValueError("--merge-shards requires --shard-count greater than one")
    if (
        args.prepare_rebalance_from_shards is not None
        and args.prepare_rebalance_from_shards < 1
    ):
        raise ValueError("--prepare-rebalance-from-shards must be positive")
    if args.prepare_rebalance_from_shards is not None and args.shard_count < 2:
        raise ValueError("Checkpoint rebalancing requires at least two target shards")
    selected_modes = sum(
        bool(value)
        for value in (
            args.merge_shards,
            args.adaptive_only,
            args.merge_adaptive_shards,
            args.prepare_rebalance_from_shards is not None,
        )
    )
    if selected_modes > 1:
        raise ValueError(
            "--merge-shards, --adaptive-only, --merge-adaptive-shards, and "
            "--prepare-rebalance-from-shards are mutually exclusive"
        )
    if args.prepare_rebalance_from_shards is not None and args.ownership_manifest:
        raise ValueError(
            "--ownership-manifest names an existing generation and cannot be "
            "combined with --prepare-rebalance-from-shards"
        )
    if args.ownership_manifest and (
        args.adaptive_only or args.merge_adaptive_shards
    ):
        raise ValueError(
            "Adaptive shards use their own family ownership and do not accept "
            "--ownership-manifest"
        )
    if args.prepare_rebalance_from_shards is not None and args.dry_run:
        raise ValueError("Checkpoint rebalancing cannot be combined with --dry-run")
    if (args.adaptive_only or args.merge_adaptive_shards) and not (
        args.adaptive_refinement
    ):
        raise ValueError(
            "Adaptive execution modes cannot be combined with "
            "--no-adaptive-refinement"
        )
    if not 0.0 < args.adaptive_axis_relative_tolerance < 1.0:
        raise ValueError(
            "--adaptive-axis-relative-tolerance must lie strictly between 0 and 1"
        )
    if not 0.0 < args.adaptive_combined_relative_tolerance < 1.0:
        raise ValueError(
            "--adaptive-combined-relative-tolerance must lie strictly between 0 and 1"
        )
    if (
        2.0 * args.adaptive_axis_relative_tolerance
        > args.adaptive_combined_relative_tolerance
    ):
        raise ValueError(
            "Twice --adaptive-axis-relative-tolerance must not exceed the "
            "combined discretization tolerance"
        )
    if not 0.0 < args.adaptive_statistical_relative_tolerance < 1.0:
        raise ValueError(
            "--adaptive-statistical-relative-tolerance must lie strictly "
            "between 0 and 1"
        )
    if not 0.0 < args.adaptive_statistical_confidence < 1.0:
        raise ValueError(
            "--adaptive-statistical-confidence must lie strictly between 0 and 1"
        )
    if args.adaptive_max_impact_levels < 1:
        raise ValueError("--adaptive-max-impact-levels must be positive")
    if args.adaptive_max_energy_levels < 1:
        raise ValueError("--adaptive-max-energy-levels must be positive")
    if args.adaptive_max_sampling_levels < 0:
        raise ValueError("--adaptive-max-sampling-levels must be non-negative")


def available_cpu_count() -> int:
    """Return CPUs available to this process, respecting scheduler affinity."""
    if hasattr(os, "sched_getaffinity"):
        try:
            affinity_count = len(os.sched_getaffinity(0))
        except OSError:
            affinity_count = 0
        if affinity_count > 0:
            return affinity_count
    return max(int(os.cpu_count() or 1), 1)


def resolve_workers(requested_workers: int) -> int:
    if requested_workers > 0:
        return int(requested_workers)
    return available_cpu_count()


def resolve_start_method(requested_method: str) -> str:
    available = multiprocessing.get_all_start_methods()
    if requested_method != "auto":
        return requested_method
    if "fork" in available:
        return "fork"
    return available[0]


def checkpoint_path_for_shard(
    output_dir: Path,
    shard_count: int,
    shard_index: int,
    ownership_generation: str | None = None,
) -> Path:
    prefix = PROJECTILE.key
    generation_suffix = (
        ""
        if ownership_generation is None
        else f".rebalance-{ownership_generation}"
    )
    if shard_count == 1:
        return output_dir / (
            f"{prefix}_charge_exchange_ctmc_checkpoint"
            f"{generation_suffix}.npz"
        )
    return output_dir / (
        f"{prefix}_charge_exchange_ctmc_checkpoint"
        f"{generation_suffix}."
        f"shard-{shard_index:05d}-of-{shard_count:05d}.npz"
    )


def rebalance_manifest_path(output_dir: Path, generation: str) -> Path:
    return output_dir / (
        f"{PROJECTILE.key}_charge_exchange_ctmc_rebalance-"
        f"{generation}.npz"
    )


def save_rebalance_manifest(
    path: Path,
    *,
    signature: str,
    generation: str,
    source_shard_count: int,
    target_shard_count: int,
    owners: np.ndarray,
    remaining_by_shard: np.ndarray,
    completed_trajectories: int,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp.npz")
    np.savez_compressed(
        temporary,
        format_version=np.asarray(1, dtype=np.int64),
        signature=np.asarray(signature),
        generation=np.asarray(generation),
        source_shard_count=np.asarray(source_shard_count, dtype=np.int64),
        target_shard_count=np.asarray(target_shard_count, dtype=np.int64),
        owners=np.asarray(owners, dtype=np.int32),
        remaining_trajectories_by_shard=np.asarray(
            remaining_by_shard, dtype=np.int64
        ),
        completed_trajectories=np.asarray(
            completed_trajectories, dtype=np.int64
        ),
        created_at=np.asarray(time.strftime("%Y-%m-%dT%H:%M:%S%z")),
    )
    os.replace(temporary, path)


def load_rebalance_manifest(
    path: Path,
    *,
    expected_signature: str,
    expected_shape: tuple[int, int, int],
    expected_shard_count: int,
) -> dict[str, np.ndarray]:
    if not path.is_file():
        raise RuntimeError(f"Missing ownership manifest {path}")
    with np.load(path, allow_pickle=False) as data:
        required = {
            "format_version",
            "signature",
            "generation",
            "source_shard_count",
            "target_shard_count",
            "owners",
            "remaining_trajectories_by_shard",
            "completed_trajectories",
            "created_at",
        }
        missing = sorted(required.difference(data.files))
        if missing:
            raise RuntimeError(
                f"Ownership manifest {path} lacks: {', '.join(missing)}"
            )
        manifest = {key: np.asarray(data[key]) for key in data.files}
    if int(manifest["format_version"]) != 1:
        raise RuntimeError(f"Unsupported ownership manifest version in {path}")
    if str(manifest["signature"].item()) != expected_signature:
        raise RuntimeError(
            f"Ownership manifest {path} belongs to a different configuration"
        )
    if int(manifest["target_shard_count"]) != expected_shard_count:
        raise RuntimeError(
            f"Ownership manifest {path} targets "
            f"{int(manifest['target_shard_count'])} shards, not "
            f"{expected_shard_count}"
        )
    owners = manifest["owners"]
    if owners.shape != expected_shape:
        raise RuntimeError(
            f"Ownership manifest {path} has shape {owners.shape}, expected "
            f"{expected_shape}"
        )
    if np.any(owners < 0) or np.any(owners >= expected_shard_count):
        raise RuntimeError(f"Ownership manifest {path} has invalid owners")
    if manifest["remaining_trajectories_by_shard"].shape != (
        expected_shard_count,
    ):
        raise RuntimeError(
            f"Ownership manifest {path} has an invalid shard-load vector"
        )
    generation = str(manifest["generation"].item())
    if not generation or any(
        character not in "0123456789abcdef" for character in generation
    ):
        raise RuntimeError(f"Ownership manifest {path} has an invalid generation")
    return manifest


def main(
    projectile_key: str,
    argv: Sequence[str] | None = None,
) -> int:
    select_projectile(projectile_key)
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.output_dir is None:
        args.output_dir = PROJECTILE.output_dir
    selected_charges = (
        PROJECTILE.default_charges if args.charges is None else args.charges
    )
    try:
        validate_args(args)
        energies = build_energy_grid(args)
        charges = parse_charges(
            selected_charges,
            args.charge_step,
            PROJECTILE.nuclear_charge,
        )
        target_bmax = parse_target_bmax(args.target_bmax_au)
        loss_bmax = parse_loss_bmax(args.loss_bmax_au)
        start_separations, minimum_integration_times = (
            resolve_paper_trajectory_boundaries(args, energies)
        )
    except ValueError as exc:
        parser.error(str(exc))

    maximum_b = max(max(target_bmax), max(loss_bmax))
    impact_au = np.linspace(0.0, maximum_b, args.impact_points)
    workers = resolve_workers(args.workers)
    start_method = resolve_start_method(args.start_method)
    config = CTMCConfig(
        backend=str(args.backend),
        trajectories=int(args.trajectories),
        trajectory_chunk_size=int(args.trajectory_chunk_size),
        target_bmax_au=target_bmax,
        loss_bmax_au=loss_bmax,
        radial_grid_points=int(args.radial_grid_points),
        start_separation_au=start_separations,
        boundary_extension_factor=float(args.boundary_extension_factor),
        minimum_integration_time_au=minimum_integration_times,
        rtol=float(args.rtol),
        atol=float(args.atol),
        retry_rtol=float(args.retry_rtol),
        retry_atol=float(args.retry_atol),
        max_step_au=float(args.max_step_au),
        minimum_radius_au=float(args.minimum_radius_au),
        maximum_relative_energy_drift=float(
            args.maximum_relative_energy_drift
        ),
        max_failure_fraction=float(args.max_failure_fraction),
        maximum_integration_steps=int(args.maximum_integration_steps),
        seed=int(args.seed),
        projectile=PROJECTILE.key,
    )

    shape = (energies.size, charges.size, impact_au.size)
    pi = np.full(shape + (len(WATER_ORBITALS),), np.nan, dtype=float)
    pc = np.full_like(pi, np.nan)
    pl = np.full(shape, np.nan, dtype=float)
    done = np.zeros(shape, dtype=bool)
    failures = np.zeros(shape, dtype=np.int64)
    successes = np.zeros(shape, dtype=np.int64)
    maximum_energy_drift = np.zeros(shape, dtype=float)
    accumulators = create_trajectory_accumulators(shape)

    signature = configuration_signature(
        energies, charges, impact_au, config
    )
    ownership_manifest: dict[str, np.ndarray] | None = None
    ownership_generation: str | None = None
    if args.ownership_manifest is not None:
        ownership_manifest = load_rebalance_manifest(
            args.ownership_manifest,
            expected_signature=signature,
            expected_shape=shape,
            expected_shard_count=args.shard_count,
        )
        ownership_generation = str(
            ownership_manifest["generation"].item()
        )
        owner_mask = (
            ownership_manifest["owners"] == args.shard_index
        )
    else:
        owner_mask = owned_point_mask(
            shape, args.shard_count, args.shard_index
        )
    checkpoint_path = checkpoint_path_for_shard(
        args.output_dir,
        args.shard_count,
        args.shard_index,
        ownership_generation,
    )
    failure_suffix = (
        ""
        if args.shard_count == 1
        else f"_shard_{args.shard_index:04d}"
    )
    if ownership_generation is not None:
        failure_suffix += f"_rebalance_{ownership_generation}"
    failure_diagnostic_path = args.output_dir / (
        f"{PROJECTILE.key}_charge_exchange_ctmc_failure"
        f"{failure_suffix}.json"
    )

    def restore_checkpoint(
        checkpoint: dict[str, np.ndarray],
        mask: np.ndarray | None = None,
    ) -> None:
        target = np.ones(shape, dtype=bool) if mask is None else mask
        point_fields = (
            ("pi", pi),
            ("pc", pc),
            ("pl", pl),
            ("done", done),
            ("failures", failures),
            ("successes", successes),
            ("maximum_energy_drift", maximum_energy_drift),
        )
        accumulator_fields = (
            ("channel_primary_events", accumulators.primary_events),
            ("channel_secondary_events", accumulators.secondary_events),
            ("channel_failures", accumulators.failures),
            ("channel_successes", accumulators.successes),
            (
                "channel_maximum_energy_drift",
                accumulators.maximum_energy_drift,
            ),
            ("channel_completed", accumulators.completed),
        )
        missing = [
            name
            for name, _ in point_fields + accumulator_fields
            if name not in checkpoint
        ]
        if missing:
            raise RuntimeError(
                "Checkpoint lacks chunk-restart fields: "
                + ", ".join(missing)
            )
        for name, destination in point_fields + accumulator_fields:
            destination[target] = checkpoint[name][target]

    def save_current_checkpoint(path: Path, *, announce: bool = False) -> None:
        save_checkpoint(
            path,
            signature=signature,
            energies=energies,
            charges=charges,
            impact_au=impact_au,
            pi=pi,
            pc=pc,
            pl=pl,
            done=done,
            failures=failures,
            successes=successes,
            maximum_energy_drift=maximum_energy_drift,
            accumulators=accumulators,
            execution_workers=workers,
            ownership_generation=ownership_generation,
        )
        if announce:
            completed_points = int(np.count_nonzero(done & owner_mask))
            owned_points = int(np.count_nonzero(owner_mask))
            completed_trajectories = int(
                np.sum(accumulators.completed[owner_mask])
            )
            tqdm.write(
                f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] "
                f"Checkpoint saved: {completed_points:,}/{owned_points:,} "
                f"points, {completed_trajectories:,} trajectories -> {path}"
            )

    def load_complete_canonical_checkpoint() -> dict[str, np.ndarray]:
        canonical_path = checkpoint_path_for_shard(args.output_dir, 1, 0)
        canonical = load_checkpoint(canonical_path, signature)
        if canonical is None:
            raise RuntimeError(
                "Adaptive refinement requires the completed canonical base "
                f"checkpoint {canonical_path}; merge the base shards first"
            )
        if not np.all(canonical["done"]):
            raise RuntimeError(
                f"Canonical base checkpoint {canonical_path} is incomplete"
            )
        return canonical

    def prepare_adaptive_runtime() -> object:
        from ctmc_adaptive_refinement import adaptive_config_from_args

        return adaptive_config_from_args(args)

    def warm_adaptive_workers() -> None:
        if workers == 1 or start_method == "fork":
            print("Preparing shared microcanonical sampling grids...")
            warm_up_initial_state_sampling(charges, config.radial_grid_points)
        if config.backend == "numba":
            assert warm_up_numba_backend is not None
            print("Compiling/loading the Numba DOP853 kernel...")
            warm_up_numba_backend()

    def prepare_rebalanced_generation(source_shard_count: int) -> Path:
        source_paths = [
            checkpoint_path_for_shard(
                args.output_dir, source_shard_count, source_index
            )
            for source_index in range(source_shard_count)
        ]
        missing_paths = [path for path in source_paths if not path.is_file()]
        if missing_paths:
            raise RuntimeError(
                "Cannot rebalance because source checkpoints are missing: "
                + ", ".join(str(path) for path in missing_paths)
            )
        source_stats = {
            path: (path.stat().st_mtime_ns, path.stat().st_size)
            for path in source_paths
        }

        for source_index, source_path in enumerate(source_paths):
            checkpoint = load_checkpoint(source_path, signature)
            assert checkpoint is not None
            for field, expected in (
                ("energies_keV_u", energies),
                ("charges", charges),
                ("impact_au", impact_au),
            ):
                if field not in checkpoint or not np.array_equal(
                    checkpoint[field], expected
                ):
                    raise RuntimeError(
                        f"Source checkpoint {source_path} has an incompatible "
                        f"{field} array"
                    )
            source_mask = owned_point_mask(
                shape, source_shard_count, source_index
            )
            outside = ~source_mask
            if np.any(checkpoint["done"][outside]) or np.any(
                checkpoint["channel_completed"][outside] != 0
            ):
                raise RuntimeError(
                    f"Source checkpoint {source_path} contains progress owned "
                    "by another shard"
                )
            restore_checkpoint(checkpoint, source_mask)

        validate_checkpoint_state(
            charges,
            impact_au,
            done,
            failures,
            successes,
            accumulators,
            config,
        )
        remaining = remaining_trajectory_counts_by_point(
            charges, impact_au, done, accumulators, config
        )
        owners = balanced_rebalance_owners(
            done, remaining, args.shard_count
        )
        generation = rebalance_generation_id(
            signature,
            source_shard_count,
            owners,
            done,
            accumulators,
        )
        remaining_by_shard = np.asarray(
            [
                int(np.sum(remaining[owners == target_index]))
                for target_index in range(args.shard_count)
            ],
            dtype=np.int64,
        )

        for target_index in tqdm(
            range(args.shard_count),
            desc="Rebalanced checkpoints",
            unit="shard",
            dynamic_ncols=True,
        ):
            target_mask = owners == target_index
            target_pi = np.full_like(pi, np.nan)
            target_pc = np.full_like(pc, np.nan)
            target_pl = np.full_like(pl, np.nan)
            target_done = np.zeros_like(done)
            target_failures = np.zeros_like(failures)
            target_successes = np.zeros_like(successes)
            target_drift = np.zeros_like(maximum_energy_drift)
            target_accumulators = create_trajectory_accumulators(shape)
            for source, destination in (
                (pi, target_pi),
                (pc, target_pc),
                (pl, target_pl),
                (done, target_done),
                (failures, target_failures),
                (successes, target_successes),
                (maximum_energy_drift, target_drift),
                (
                    accumulators.primary_events,
                    target_accumulators.primary_events,
                ),
                (
                    accumulators.secondary_events,
                    target_accumulators.secondary_events,
                ),
                (accumulators.failures, target_accumulators.failures),
                (accumulators.successes, target_accumulators.successes),
                (
                    accumulators.maximum_energy_drift,
                    target_accumulators.maximum_energy_drift,
                ),
                (accumulators.completed, target_accumulators.completed),
            ):
                destination[target_mask] = source[target_mask]
            target_path = checkpoint_path_for_shard(
                args.output_dir,
                args.shard_count,
                target_index,
                generation,
            )
            save_checkpoint(
                target_path,
                signature=signature,
                energies=energies,
                charges=charges,
                impact_au=impact_au,
                pi=target_pi,
                pc=target_pc,
                pl=target_pl,
                done=target_done,
                failures=target_failures,
                successes=target_successes,
                maximum_energy_drift=target_drift,
                accumulators=target_accumulators,
                execution_workers=workers,
                ownership_generation=generation,
            )

        changed_sources = [
            path
            for path, frozen_stat in source_stats.items()
            if not path.is_file()
            or (path.stat().st_mtime_ns, path.stat().st_size) != frozen_stat
        ]
        if changed_sources:
            raise RuntimeError(
                "Source checkpoints changed during rebalancing; no manifest "
                "was published. Stop all source writers and retry. Changed: "
                + ", ".join(str(path) for path in changed_sources)
            )

        manifest_path = rebalance_manifest_path(args.output_dir, generation)
        save_rebalance_manifest(
            manifest_path,
            signature=signature,
            generation=generation,
            source_shard_count=source_shard_count,
            target_shard_count=args.shard_count,
            owners=owners,
            remaining_by_shard=remaining_by_shard,
            completed_trajectories=int(np.sum(accumulators.completed)),
        )
        print(
            f"Rebalanced {int(np.count_nonzero(~done)):,} unfinished points "
            f"across {args.shard_count} shards; remaining trajectories per "
            f"shard: {int(np.min(remaining_by_shard)):,}--"
            f"{int(np.max(remaining_by_shard)):,}."
        )
        print(f"Ownership manifest: {manifest_path}")
        return manifest_path

    def run_single_node_adaptive(
        canonical: dict[str, np.ndarray],
    ) -> tuple[Path, Path, Path, Path]:
        from ctmc_adaptive_refinement import (
            merge_adaptive_families,
            run_adaptive_shard,
            write_adaptive_manifest,
        )

        adaptive = prepare_adaptive_runtime()
        manifest = write_adaptive_manifest(
            args.output_dir,
            base_signature=signature,
            energies=energies,
            charges=charges,
            adaptive=adaptive,
        )
        print(f"Adaptive refinement manifest: {manifest}")
        warm_adaptive_workers()
        run_adaptive_shard(
            output_dir=args.output_dir,
            base_signature=signature,
            base_checkpoint=canonical,
            base_config=config,
            workers=workers,
            start_method=start_method,
            pending_factor=args.pending_factor,
            checkpoint_every=args.checkpoint_every,
            checkpoint_seconds=args.checkpoint_seconds,
            shard_count=1,
            shard_index=0,
            adaptive=adaptive,
        )
        return merge_adaptive_families(
            output_dir=args.output_dir,
            base_signature=signature,
            base_checkpoint=canonical,
            base_config=config,
            adaptive=adaptive,
        )

    if args.prepare_rebalance_from_shards is not None:
        prepare_rebalanced_generation(args.prepare_rebalance_from_shards)
        return 0

    if args.adaptive_only or args.merge_adaptive_shards:
        from ctmc_adaptive_refinement import (
            merge_adaptive_families,
            run_adaptive_shard,
            write_adaptive_manifest,
        )

        canonical = load_complete_canonical_checkpoint()
        adaptive = prepare_adaptive_runtime()
        manifest = write_adaptive_manifest(
            args.output_dir,
            base_signature=signature,
            energies=energies,
            charges=charges,
            adaptive=adaptive,
        )
        if args.merge_adaptive_shards:
            paths = merge_adaptive_families(
                output_dir=args.output_dir,
                base_signature=signature,
                base_checkpoint=canonical,
                base_config=config,
                adaptive=adaptive,
            )
            print("Wrote adaptively converged outputs:")
            for path in paths:
                print(f"  {path}")
            return 0
        print(f"Adaptive refinement manifest: {manifest}")
        if not args.dry_run:
            warm_adaptive_workers()
        return run_adaptive_shard(
            output_dir=args.output_dir,
            base_signature=signature,
            base_checkpoint=canonical,
            base_config=config,
            workers=workers,
            start_method=start_method,
            pending_factor=args.pending_factor,
            checkpoint_every=args.checkpoint_every,
            checkpoint_seconds=args.checkpoint_seconds,
            shard_count=args.shard_count,
            shard_index=args.shard_index,
            adaptive=adaptive,
            dry_run=args.dry_run,
        )

    if args.merge_shards:
        workers_per_shard: list[int] = []
        for shard_index in range(args.shard_count):
            shard_path = checkpoint_path_for_shard(
                args.output_dir,
                args.shard_count,
                shard_index,
                ownership_generation,
            )
            checkpoint = load_checkpoint(
                shard_path,
                signature,
                ownership_generation,
            )
            if checkpoint is None:
                raise RuntimeError(f"Missing shard checkpoint {shard_path}")
            shard_mask = (
                owned_point_mask(shape, args.shard_count, shard_index)
                if ownership_manifest is None
                else ownership_manifest["owners"] == shard_index
            )
            if not np.all(checkpoint["done"][shard_mask]):
                completed = int(np.count_nonzero(checkpoint["done"][shard_mask]))
                total = int(np.count_nonzero(shard_mask))
                raise RuntimeError(
                    f"Shard {shard_index} is incomplete: "
                    f"{completed}/{total} points in {shard_path}"
                )
            workers_per_shard.append(
                int(
                    np.asarray(
                        checkpoint.get("execution_workers", workers)
                    ).item()
                )
            )
            restore_checkpoint(checkpoint, shard_mask)
            print(f"Merged shard {shard_index + 1}/{args.shard_count}: {shard_path}")
        if not np.all(done):
            raise RuntimeError("Merged shard set did not cover the complete grid")
        canonical_checkpoint = checkpoint_path_for_shard(
            args.output_dir, 1, 0
        )
        save_current_checkpoint(canonical_checkpoint)
        if args.adaptive_refinement:
            from ctmc_adaptive_refinement import (
                write_adaptive_manifest,
            )

            manifest = write_adaptive_manifest(
                args.output_dir,
                base_signature=signature,
                energies=energies,
                charges=charges,
                adaptive=prepare_adaptive_runtime(),
            )
            print(
                "Merged the fixed base grid. Final tables are withheld until "
                "the default adaptive refinement reaches the requested "
                f"0.5% tolerance. Manifest: {manifest}\n"
                "Run the same shard array with --adaptive-only, then run one "
                "--merge-adaptive-shards command."
            )
            return 0
        paths = write_outputs(
            args.output_dir,
            energies=energies,
            charges=charges,
            impact_au=impact_au,
            pi=pi,
            pc=pc,
            pl=pl,
            failures=failures,
            successes=successes,
            maximum_energy_drift=maximum_energy_drift,
            config=config,
            workers=workers,
            shard_count=args.shard_count,
            workers_per_shard=workers_per_shard,
            signature=signature,
        )
        print("Wrote merged outputs:")
        for path in paths:
            print(f"  {path}")
        return 0

    if not args.no_resume:
        checkpoint = load_checkpoint(
            checkpoint_path,
            signature,
            ownership_generation,
        )
        if checkpoint is not None:
            restore_checkpoint(checkpoint)
            owned_completed = int(np.count_nonzero(done & owner_mask))
            owned_total = int(np.count_nonzero(owner_mask))
            print(
                f"Resumed {owned_completed}/{owned_total} shard points "
                f"from {checkpoint_path}"
            )

    pending_mask = owner_mask & ~done
    pending_points = int(np.count_nonzero(pending_mask))
    estimated, estimated_chunks = estimate_remaining_trajectory_count(
        charges,
        impact_au,
        done,
        accumulators,
        config,
        owner_mask,
    )
    print(
        f"Grid: {energies.size} energies x {charges.size} charge states x "
        f"{impact_au.size} impact parameters"
    )
    if args.shard_count > 1:
        print(
            f"Shard: {args.shard_index}/{args.shard_count - 1}; "
            f"owned points: {int(np.count_nonzero(owner_mask)):,}"
        )
    print(
        f"Pending probability points: {pending_points:,}; "
        f"remaining trajectories: {estimated:,}; "
        f"work chunks: {estimated_chunks:,}"
    )
    print(
        f"Backend: {config.backend}; local workers: {workers}; "
        f"chunk size: {config.trajectory_chunk_size}; "
        f"start method: {start_method}"
    )
    if args.dry_run:
        if args.adaptive_refinement:
            from ctmc_adaptive_refinement import adaptive_family_count

            print(
                "Adaptive refinement (default): "
                f"{adaptive_family_count(energies, charges):,} independent "
                "charge/energy families; axis/combined discretization targets "
                f"{args.adaptive_axis_relative_tolerance:.3%}/"
                f"{args.adaptive_combined_relative_tolerance:.3%}; "
                f"statistical target "
                f"{args.adaptive_statistical_relative_tolerance:.3%} at "
                f"{args.adaptive_statistical_confidence:.1%} confidence."
            )
        return 0

    if pending_points == 0:
        if args.shard_count > 1:
            print(
                f"Shard {args.shard_index}/{args.shard_count - 1} is complete. "
                f"Run --merge-shards --shard-count {args.shard_count} after "
                "all shards finish."
            )
            return 0
        if args.adaptive_refinement:
            save_current_checkpoint(checkpoint_path)
            paths = run_single_node_adaptive(
                load_complete_canonical_checkpoint()
            )
            print("Wrote adaptively converged outputs:")
            for path in paths:
                print(f"  {path}")
            return 0
        paths = write_outputs(
            args.output_dir,
            energies=energies,
            charges=charges,
            impact_au=impact_au,
            pi=pi,
            pc=pc,
            pl=pl,
            failures=failures,
            successes=successes,
            maximum_energy_drift=maximum_energy_drift,
            config=config,
            workers=workers,
            shard_count=1,
            signature=signature,
        )
        print("Wrote:")
        for path in paths:
            print(f"  {path}")
        return 0

    if workers == 1 or start_method == "fork":
        print("Preparing shared microcanonical sampling grids...")
        warm_up_initial_state_sampling(charges, config.radial_grid_points)

    if config.backend == "numba":
        assert warm_up_numba_backend is not None
        print("Compiling/loading the Numba DOP853 kernel...")
        warm_up_numba_backend()

    previous_signal_handlers: dict[int, signal.Handlers] = {}

    def handle_scheduler_termination(
        signal_number: int,
        _: object,
    ) -> None:
        signal_name = signal.Signals(signal_number).name
        for installed_signal in previous_signal_handlers:
            signal.signal(installed_signal, signal.SIG_IGN)
        tqdm.write(
            f"Received {signal_name}; stopping workers and saving checkpoint..."
        )
        raise KeyboardInterrupt

    for signal_name in ("SIGTERM", "SIGUSR1"):
        termination_signal = getattr(signal, signal_name, None)
        if termination_signal is not None:
            previous_signal_handlers[termination_signal] = signal.getsignal(
                termination_signal
            )
            signal.signal(termination_signal, handle_scheduler_termination)

    task_iterator = iter_pending_trajectory_tasks(
        energies,
        charges,
        impact_au,
        done,
        accumulators,
        config,
        owner_mask,
    )
    trajectory_progress = tqdm(
        total=estimated,
        desc="Trajectories",
        unit="traj",
        unit_scale=True,
        dynamic_ncols=True,
        position=0,
    )
    point_progress = tqdm(
        total=pending_points,
        desc="Grid points",
        unit="point",
        dynamic_ncols=True,
        position=1,
    )

    completed_since_checkpoint = 0
    last_checkpoint_time = time.monotonic()
    buffered_results: dict[
        tuple[int, int, int, int],
        dict[
            int,
            tuple[
                int, int, int, int, int, int, int, int, int, int, float
            ],
        ],
    ] = {}

    def accept_result(
        result: tuple[
            int, int, int, int, int, int, int, int, int, int, float
        ],
    ) -> int:
        """Buffer out-of-order chunks and commit only contiguous prefixes."""
        trajectory_progress.update(result[5])
        key = result[:4]
        start = result[4]
        expected = int(accumulators.completed[key])
        if start < expected:
            raise RuntimeError(f"Duplicate CTMC chunk result for {key}@{start}")
        channel_buffer = buffered_results.setdefault(key, {})
        if start in channel_buffer:
            raise RuntimeError(f"Duplicate buffered CTMC chunk for {key}@{start}")
        channel_buffer[start] = result

        completed_points = 0
        while expected in channel_buffer:
            contiguous = channel_buffer.pop(expected)
            completed_points += int(
                _commit_trajectory_chunk(
                    contiguous,
                    energies=energies,
                    charges=charges,
                    impact_au=impact_au,
                    config=config,
                    accumulators=accumulators,
                    pi=pi,
                    pc=pc,
                    pl=pl,
                    done=done,
                    failures=failures,
                    successes=successes,
                    maximum_energy_drift=maximum_energy_drift,
                )
            )
            expected += contiguous[5]
        if not channel_buffer:
            buffered_results.pop(key, None)
        return completed_points

    try:
        try:
            if workers == 1:
                _init_worker(config)
                results: Iterable[
                    tuple[
                        int,
                        int,
                        int,
                        int,
                        int,
                        int,
                        int,
                        int,
                        int,
                        int,
                        float,
                    ]
                ] = map(_compute_trajectory_chunk, task_iterator)
                for result in results:
                    completed_points = accept_result(result)
                    point_progress.update(completed_points)
                    completed_since_checkpoint += completed_points
                    now = time.monotonic()
                    if (
                        completed_since_checkpoint >= args.checkpoint_every
                        or (
                            args.checkpoint_seconds > 0.0
                            and now - last_checkpoint_time
                            >= args.checkpoint_seconds
                        )
                    ):
                        save_current_checkpoint(checkpoint_path, announce=True)
                        completed_since_checkpoint = 0
                        last_checkpoint_time = now
            else:
                process_context = multiprocessing.get_context(start_method)
                executor = ProcessPoolExecutor(
                    max_workers=workers,
                    initializer=_init_worker,
                    initargs=(config, True),
                    mp_context=process_context,
                )
                try:
                    parallel_results = bounded_chunk_results(
                        executor,
                        task_iterator,
                        maximum_pending=max(args.pending_factor * workers, 1),
                    )
                    for result in parallel_results:
                        completed_points = accept_result(result)
                        point_progress.update(completed_points)
                        completed_since_checkpoint += completed_points
                        now = time.monotonic()
                        if (
                            completed_since_checkpoint
                            >= args.checkpoint_every
                            or (
                                args.checkpoint_seconds > 0.0
                                and now - last_checkpoint_time
                                >= args.checkpoint_seconds
                            )
                        ):
                            save_current_checkpoint(
                                checkpoint_path, announce=True
                            )
                            completed_since_checkpoint = 0
                            last_checkpoint_time = now
                except BaseException:
                    terminate_process_pool(executor)
                    raise
                else:
                    executor.shutdown(wait=True)
        except TrajectoryIntegrationFailure as error:
            detail = error.args[0] if error.args else str(error)
            save_failure_diagnostic(
                failure_diagnostic_path,
                signature=signature,
                checkpoint_path=checkpoint_path,
                detail=detail,
            )
            tqdm.write(
                "Trajectory integration failed; exact identity saved to "
                f"{failure_diagnostic_path}"
            )
            raise
        finally:
            save_current_checkpoint(checkpoint_path, announce=True)
    finally:
        point_progress.close()
        trajectory_progress.close()
        for termination_signal, previous_handler in (
            previous_signal_handlers.items()
        ):
            signal.signal(termination_signal, previous_handler)

    if not np.all(done[owner_mask]):
        raise RuntimeError(
            "CTMC shard is incomplete; its checkpoint was preserved"
        )
    failure_diagnostic_path.unlink(missing_ok=True)
    if args.shard_count > 1:
        print(
            f"Shard {args.shard_index}/{args.shard_count - 1} complete: "
            f"{checkpoint_path}\n"
            f"After every shard completes, run this program with "
            f"--shard-count {args.shard_count} --merge-shards and the same "
            "physics/grid arguments."
        )
        return 0

    if args.adaptive_refinement:
        paths = run_single_node_adaptive(load_complete_canonical_checkpoint())
        print("Wrote adaptively converged outputs:")
        for path in paths:
            print(f"  {path}")
        return 0

    paths = write_outputs(
        args.output_dir,
        energies=energies,
        charges=charges,
        impact_au=impact_au,
        pi=pi,
        pc=pc,
        pl=pl,
        failures=failures,
        successes=successes,
        maximum_energy_drift=maximum_energy_drift,
        config=config,
        workers=workers,
        shard_count=1,
        signature=signature,
    )
    print("Wrote:")
    for path in paths:
        print(f"  {path}")
    return 0


