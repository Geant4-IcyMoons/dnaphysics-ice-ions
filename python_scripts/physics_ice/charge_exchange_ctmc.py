def owned_point_mask(
    shape: tuple[int, int, int],
    shard_count: int,
    shard_index: int,
) -> np.ndarray:
    """
    Return the stable charge-major partition owned by one compute job.

    Charge is the fastest-varying index. Consequently, when the shard count
    is an integer multiple of the selected charge count, every charge is
    handled by the same number of shards. Other shard counts still give
    disjoint, near-equal point partitions.
    """
    energy_count, charge_count, impact_count = shape
    energy_index, charge_index, impact_index = np.indices(
        (energy_count, charge_count, impact_count),
        dtype=np.int64,
    )
    point_index = charge_index + charge_count * (
        impact_index + impact_count * energy_index
    )
    return point_index % int(shard_count) == int(shard_index)


def _active_channels(
    charge_state: int,
    impact_parameter_au: float,
    config: CTMCConfig,
) -> tuple[int, ...]:
    channels = [
        orbital_index
        for orbital_index, bmax in enumerate(config.target_bmax_au)
        if impact_parameter_au <= bmax
    ]
    if (
        charge_state in PROJECTILE_OUTER_ORBITAL
        and impact_parameter_au
        <= config.loss_bmax_au[int(charge_state)]
    ):
        channels.append(LOSS_CHANNEL_INDEX)
    return tuple(channels)


def iter_pending_trajectory_tasks(
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    done: np.ndarray,
    accumulators: TrajectoryAccumulators,
    config: CTMCConfig,
    owner_mask: np.ndarray,
) -> Iterable[
    tuple[
        int,
        int,
        float,
        int,
        int,
        float,
        int,
        int,
        int,
        float,
        float,
    ]
]:
    """
    Yield bounded chunks, longest physical trajectories first.

    Low projectile energies have the longest integration interval. Starting
    them first follows longest-processing-time scheduling and avoids a slow
    low-energy tail after most workers have become idle.
    """
    for energy_index, energy in enumerate(energies):
        for charge_index, charge in enumerate(charges):
            for impact_index, impact in enumerate(impact_au):
                point = (energy_index, charge_index, impact_index)
                if done[point] or not owner_mask[point]:
                    continue
                for channel_index in _active_channels(
                    int(charge), float(impact), config
                ):
                    start = int(
                        accumulators.completed[point + (channel_index,)]
                    )
                    if start < 0 or start > config.trajectories:
                        raise RuntimeError(
                            "Invalid completed-trajectory count in checkpoint "
                            f"at point={point}, channel={channel_index}: {start}"
                        )
                    while start < config.trajectories:
                        count = min(
                            config.trajectory_chunk_size,
                            config.trajectories - start,
                        )
                        yield (
                            energy_index,
                            charge_index,
                            float(energy),
                            int(charge),
                            impact_index,
                            float(impact),
                            channel_index,
                            start,
                            count,
                            config.start_separation_au[energy_index],
                            config.minimum_integration_time_au[energy_index],
                        )
                        start += count


def estimate_remaining_trajectory_count(
    charges: np.ndarray,
    impact_au: np.ndarray,
    done: np.ndarray,
    accumulators: TrajectoryAccumulators,
    config: CTMCConfig,
    owner_mask: np.ndarray,
) -> tuple[int, int]:
    """Return the remaining trajectory and work-chunk counts for this shard."""
    trajectories = 0
    chunks = 0
    for energy_index in range(done.shape[0]):
        for charge_index, charge in enumerate(charges):
            for impact_index, impact in enumerate(impact_au):
                point = (energy_index, charge_index, impact_index)
                if done[point] or not owner_mask[point]:
                    continue
                for channel_index in _active_channels(
                    int(charge), float(impact), config
                ):
                    completed = int(
                        accumulators.completed[point + (channel_index,)]
                    )
                    remaining = config.trajectories - completed
                    if remaining < 0:
                        raise RuntimeError(
                            "Checkpoint contains too many completed trajectories"
                        )
                    trajectories += remaining
                    chunks += math.ceil(
                        remaining / config.trajectory_chunk_size
                    )
    return int(trajectories), int(chunks)


def remaining_trajectory_counts_by_point(
    charges: np.ndarray,
    impact_au: np.ndarray,
    done: np.ndarray,
    accumulators: TrajectoryAccumulators,
    config: CTMCConfig,
) -> np.ndarray:
    """Return the exact uncommitted trajectory count at every grid point."""
    remaining = np.zeros(done.shape, dtype=np.int64)
    for energy_index in range(done.shape[0]):
        for charge_index, charge in enumerate(charges):
            for impact_index, impact in enumerate(impact_au):
                point = (energy_index, charge_index, impact_index)
                if done[point]:
                    continue
                for channel_index in _active_channels(
                    int(charge), float(impact), config
                ):
                    completed = int(
                        accumulators.completed[point + (channel_index,)]
                    )
                    if completed < 0 or completed > config.trajectories:
                        raise RuntimeError(
                            "Invalid completed-trajectory count at "
                            f"point={point}, channel={channel_index}: "
                            f"{completed}"
                        )
                    remaining[point] += config.trajectories - completed
                if remaining[point] <= 0:
                    raise RuntimeError(
                        "Incomplete point has no remaining trajectories: "
                        f"{point}"
                    )
    return remaining


def balanced_rebalance_owners(
    done: np.ndarray,
    remaining: np.ndarray,
    shard_count: int,
) -> np.ndarray:
    """
    Assign every point to one shard while balancing each energy layer.

    Completed points retain the ordinary stable modulo partition. Within
    every unfinished energy layer, longest remaining points are assigned to
    the shard with the least work in that layer, then the least total work.
    This spreads the intrinsically slow low-energy tail without introducing a
    physics-dependent runtime fit.
    """
    if done.shape != remaining.shape:
        raise ValueError("done and remaining arrays must have the same shape")
    if done.ndim != 3:
        raise ValueError("CTMC ownership arrays must be three-dimensional")
    if shard_count < 1:
        raise ValueError("shard_count must be positive")
    if np.any(remaining < 0):
        raise ValueError("remaining trajectory counts must be non-negative")
    if np.any(remaining[done] != 0):
        raise ValueError("completed points cannot contain remaining work")
    if np.any(remaining[~done] <= 0):
        raise ValueError("every incomplete point must contain remaining work")

    owners = np.empty(done.shape, dtype=np.int32)
    for shard_index in range(shard_count):
        owners[owned_point_mask(done.shape, shard_count, shard_index)] = (
            shard_index
        )

    total_load = np.zeros(shard_count, dtype=np.int64)
    for energy_index in range(done.shape[0]):
        energy_load = np.zeros(shard_count, dtype=np.int64)
        unfinished = [
            (
                int(remaining[energy_index, charge_index, impact_index]),
                charge_index,
                impact_index,
            )
            for charge_index in range(done.shape[1])
            for impact_index in range(done.shape[2])
            if not done[energy_index, charge_index, impact_index]
        ]
        unfinished.sort(key=lambda item: (-item[0], item[1], item[2]))
        for point_load, charge_index, impact_index in unfinished:
            owner = min(
                range(shard_count),
                key=lambda candidate: (
                    int(energy_load[candidate]),
                    int(total_load[candidate]),
                    candidate,
                ),
            )
            owners[energy_index, charge_index, impact_index] = owner
            energy_load[owner] += point_load
            total_load[owner] += point_load
    return owners


def validate_checkpoint_state(
    charges: np.ndarray,
    impact_au: np.ndarray,
    done: np.ndarray,
    failures: np.ndarray,
    successes: np.ndarray,
    accumulators: TrajectoryAccumulators,
    config: CTMCConfig,
) -> None:
    """Reject incomplete, duplicated, or internally inconsistent raw counts."""
    count_arrays = (
        accumulators.primary_events,
        accumulators.secondary_events,
        accumulators.failures,
        accumulators.successes,
        accumulators.completed,
    )
    if any(np.any(values < 0) for values in count_arrays):
        raise RuntimeError("Checkpoint contains a negative trajectory count")
    if np.any(accumulators.completed > config.trajectories):
        raise RuntimeError("Checkpoint contains too many completed trajectories")
    if not np.array_equal(
        accumulators.failures + accumulators.successes,
        accumulators.completed,
    ):
        raise RuntimeError("Checkpoint channel accounting is inconsistent")
    if np.any(
        accumulators.primary_events + accumulators.secondary_events
        > accumulators.successes
    ):
        raise RuntimeError("Checkpoint event counts exceed successful trajectories")

    for energy_index in range(done.shape[0]):
        for charge_index, charge in enumerate(charges):
            for impact_index, impact in enumerate(impact_au):
                point = (energy_index, charge_index, impact_index)
                active = _active_channels(int(charge), float(impact), config)
                active_mask = np.zeros(
                    accumulators.completed.shape[-1], dtype=bool
                )
                active_mask[list(active)] = True
                point_completed = accumulators.completed[point]
                if np.any(point_completed[~active_mask] != 0):
                    raise RuntimeError(
                        f"Inactive channel contains work at point={point}"
                    )
                is_complete = bool(
                    active
                    and np.all(point_completed[active_mask] == config.trajectories)
                )
                if bool(done[point]) != is_complete:
                    raise RuntimeError(
                        "Checkpoint done flag disagrees with raw channels at "
                        f"point={point}"
                    )
                if done[point]:
                    expected_failures = int(
                        np.sum(accumulators.failures[point][active_mask])
                    )
                    expected_successes = int(
                        np.sum(accumulators.successes[point][active_mask])
                    )
                    if (
                        int(failures[point]) != expected_failures
                        or int(successes[point]) != expected_successes
                    ):
                        raise RuntimeError(
                            "Checkpoint point accounting disagrees with raw "
                            f"channels at point={point}"
                        )


def rebalance_generation_id(
    signature: str,
    source_shard_count: int,
    owners: np.ndarray,
    done: np.ndarray,
    accumulators: TrajectoryAccumulators,
) -> str:
    """Fingerprint the exact frozen raw state and its new ownership map."""
    digest = hashlib.sha256()
    digest.update(signature.encode("ascii"))
    digest.update(np.asarray(source_shard_count, dtype=np.int64).tobytes())
    for values in (
        owners,
        done,
        accumulators.primary_events,
        accumulators.secondary_events,
        accumulators.failures,
        accumulators.successes,
        accumulators.maximum_energy_drift,
        accumulators.completed,
    ):
        contiguous = np.ascontiguousarray(values)
        digest.update(str(contiguous.dtype).encode("ascii"))
        digest.update(np.asarray(contiguous.shape, dtype=np.int64).tobytes())
        digest.update(contiguous.tobytes())
    return digest.hexdigest()[:16]


def _commit_trajectory_chunk(
    result: tuple[int, int, int, int, int, int, int, int, int, int, float],
    *,
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    config: CTMCConfig,
    accumulators: TrajectoryAccumulators,
    pi: np.ndarray,
    pc: np.ndarray,
    pl: np.ndarray,
    done: np.ndarray,
    failures: np.ndarray,
    successes: np.ndarray,
    maximum_energy_drift: np.ndarray,
) -> bool:
    """Commit one contiguous chunk and finalize its point when complete."""
    (
        energy_index,
        charge_index,
        impact_index,
        channel_index,
        trajectory_start,
        trajectory_count,
        primary_events,
        secondary_events,
        chunk_failures,
        chunk_successes,
        chunk_maximum_drift,
    ) = result
    point = (energy_index, charge_index, impact_index)
    channel = point + (channel_index,)
    expected_start = int(accumulators.completed[channel])
    if trajectory_start != expected_start:
        raise RuntimeError(
            "Non-contiguous CTMC chunk commit: "
            f"expected {expected_start}, received {trajectory_start} "
            f"at point={point}, channel={channel_index}"
        )
    if trajectory_count != chunk_failures + chunk_successes:
        raise RuntimeError("Trajectory chunk accounting is inconsistent")

    accumulators.primary_events[channel] += primary_events
    accumulators.secondary_events[channel] += secondary_events
    accumulators.failures[channel] += chunk_failures
    accumulators.successes[channel] += chunk_successes
    accumulators.maximum_energy_drift[channel] = max(
        accumulators.maximum_energy_drift[channel],
        chunk_maximum_drift,
    )
    accumulators.completed[channel] += trajectory_count
    if accumulators.completed[channel] > config.trajectories:
        raise RuntimeError("Committed more trajectories than requested")

    if done[point]:
        return False
    active_channels = _active_channels(
        int(charges[charge_index]),
        float(impact_au[impact_index]),
        config,
    )
    if any(
        accumulators.completed[point + (active_channel,)]
        < config.trajectories
        for active_channel in active_channels
    ):
        return False

    pi[point] = 0.0
    pc[point] = 0.0
    pl[point] = 0.0
    for active_channel in active_channels:
        channel = point + (active_channel,)
        channel_successes = int(accumulators.successes[channel])
        if channel_successes == 0:
            raise RuntimeError(
                "All trajectories failed at "
                f"E={energies[energy_index]:g} keV/u, "
                f"q={charges[charge_index]}, b={impact_au[impact_index]:g}, "
                f"channel={active_channel}"
            )
        probability = (
            accumulators.primary_events[channel] / channel_successes
        )
        if active_channel < LOSS_CHANNEL_INDEX:
            pi[point + (active_channel,)] = probability
            pc[point + (active_channel,)] = (
                accumulators.secondary_events[channel] / channel_successes
            )
        else:
            pl[point] = probability

    point_failures = int(
        sum(
            accumulators.failures[point + (active_channel,)]
            for active_channel in active_channels
        )
    )
    point_successes = int(
        sum(
            accumulators.successes[point + (active_channel,)]
            for active_channel in active_channels
        )
    )
    attempted = point_failures + point_successes
    if attempted and point_failures / attempted > config.max_failure_fraction:
        raise RuntimeError(
            f"Trajectory failure fraction {point_failures / attempted:.3%} "
            f"exceeds limit {config.max_failure_fraction:.3%} at "
            f"q={charges[charge_index]}, b={impact_au[impact_index]:g} a.u."
        )
    failures[point] = point_failures
    successes[point] = point_successes
    maximum_energy_drift[point] = max(
        accumulators.maximum_energy_drift[
            point + (active_channel,)
        ]
        for active_channel in active_channels
    )
    done[point] = True
    return True


def bounded_chunk_results(
    executor: ProcessPoolExecutor,
    tasks: Iterable[
        tuple[
            int,
            int,
            float,
            int,
            int,
            float,
            int,
            int,
            int,
            float,
            float,
        ]
    ],
    maximum_pending: int,
) -> Iterable[
    tuple[int, int, int, int, int, int, int, int, int, int, float]
]:
    """Keep a bounded worker queue and return chunks as soon as they finish."""
    task_iterator = iter(tasks)
    pending = set()
    for _ in range(maximum_pending):
        try:
            task = next(task_iterator)
        except StopIteration:
            break
        pending.add(executor.submit(_compute_trajectory_chunk, task))

    while pending:
        completed, pending = wait(pending, return_when=FIRST_COMPLETED)
        for future in completed:
            yield future.result()
            try:
                task = next(task_iterator)
            except StopIteration:
                continue
            pending.add(executor.submit(_compute_trajectory_chunk, task))


def terminate_process_pool(executor: ProcessPoolExecutor) -> None:
    """Stop in-flight chunks promptly during a scheduler/user interruption."""
    terminate_workers = getattr(executor, "terminate_workers", None)
    if terminate_workers is not None:
        terminate_workers()
        return

    # Python <3.14 has no public immediate-termination API. The fallback is
    # deliberately confined to the exceptional shutdown path.
    processes = list(getattr(executor, "_processes", {}).values())
    for process in processes:
        if process.is_alive():
            process.terminate()
    # Do not wait for every process join: batch schedulers commonly escalate
    # SIGTERM to SIGKILL after a short grace period. The parent must reach its
    # atomic checkpoint write first.
    executor.shutdown(wait=False, cancel_futures=True)


def parse_target_bmax(text: str | None) -> tuple[float, ...]:
    if text is None:
        raise ValueError(
            "--target-bmax-au is required because channel cutoffs must be "
            "established by negligible-interaction convergence"
        )
    values = tuple(
        float(part.strip())
        for part in text.replace(";", ",").split(",")
        if part.strip()
    )
    if len(values) != len(WATER_ORBITALS):
        raise ValueError(
            "--target-bmax-au requires five comma-separated "
            "values ordered as 1b1,3a1,1b2,2a1,1a1"
        )
    if any(not math.isfinite(value) or value <= 0.0 for value in values):
        raise ValueError(
            "Target bmax values must be finite and positive"
        )
    if PROJECTILE.key == "carbon":
        if any(value < 1.0 or value > 25.0 for value in values):
            raise ValueError(
                "Carbon target bmax values must stay within the paper's "
                "1-to-25 a.u. range"
            )
        if not math.isclose(values[0], 25.0) or not math.isclose(
            values[-1], 1.0
        ):
            raise ValueError(
                "The carbon paper specifies bmax=25 a.u. for the outermost "
                "1b1 shell and bmax=1 a.u. for the innermost 1a1 shell"
            )
    if any(first < second for first, second in zip(values, values[1:])):
        raise ValueError(
            "Target bmax values must not increase from outermost to "
            "innermost orbital"
        )
    return values


def parse_loss_bmax(text: str | None) -> tuple[float, ...]:
    if text is None:
        raise ValueError(
            "--loss-bmax-au is required because charge-specific cutoffs must "
            "be established by negligible-interaction convergence"
        )
    values = tuple(
        float(part.strip())
        for part in text.replace(";", ",").split(",")
        if part.strip()
    )
    if len(values) != len(PROJECTILE_OUTER_ORBITAL):
        labels = ",".join(
            f"{PROJECTILE.symbol}{q}{'+' if q else ''}"
            for q in PROJECTILE_OUTER_ORBITAL
        )
        raise ValueError(
            f"--loss-bmax-au requires {len(PROJECTILE_OUTER_ORBITAL)} "
            f"comma-separated values ordered as {labels}"
        )
    if any(not math.isfinite(value) or value <= 0.0 for value in values):
        raise ValueError(
            "Projectile-loss bmax values must be finite and positive"
        )
    if PROJECTILE.key == "carbon" and any(
        value < 10.0 or value > 20.0 for value in values
    ):
        raise ValueError(
            "Carbon projectile-loss bmax values must stay within the paper's "
            "10-to-20 a.u. range"
        )
    return values


