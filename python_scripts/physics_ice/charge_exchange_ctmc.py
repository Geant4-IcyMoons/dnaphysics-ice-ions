def _init_worker(
    config: CTMCConfig,
    reset_termination_signals: bool = False,
) -> None:
    global _WORKER_CONFIG
    _WORKER_CONFIG = config
    select_projectile(config.projectile)
    if reset_termination_signals:
        # The parent converts scheduler termination signals into a graceful
        # checkpoint. Workers should terminate immediately if PBS signals the
        # whole process group, allowing the parent to preserve committed data.
        for signal_name in ("SIGTERM", "SIGUSR1"):
            worker_signal = getattr(signal, signal_name, None)
            if worker_signal is not None:
                signal.signal(worker_signal, signal.SIG_DFL)


def _channel_rng(
    master_seed: int,
    energy_index: int,
    charge_state: int,
    impact_index: int,
    channel_index: int,
    trajectory_start: int,
) -> np.random.Generator:
    """Return the deterministic stream at one channel trajectory offset."""
    seed = np.random.SeedSequence(
        [
            int(master_seed),
            int(energy_index),
            int(charge_state),
            int(impact_index),
            int(channel_index),
        ]
    )
    bit_generator = np.random.PCG64(seed)
    bit_generator.advance(
        int(trajectory_start) * RANDOM_DRAWS_PER_TRAJECTORY
    )
    return np.random.Generator(bit_generator)


def _compute_trajectory_chunk(
    task: tuple[
        int,
        int,
        float,
        int,
        int,
        float,
        int,
        int,
        int,
        float,
        float,
    ],
) -> tuple[int, int, int, int, int, int, int, int, int, int, float]:
    """
    Simulate a bounded trajectory chunk for one point and physical channel.

    The two event counters are ``(ionized, captured)`` for a target orbital and
    ``(lost, 0)`` for the projectile-loss channel. Returning raw integer counts
    lets the parent aggregate without worker locks and checkpoint partial work.
    """
    (
        energy_index,
        charge_index,
        energy,
        charge,
        impact_index,
        impact,
        channel_index,
        trajectory_start,
        trajectory_count,
        start_separation_au,
        minimum_integration_time_au,
    ) = task
    if _WORKER_CONFIG is None:
        raise RuntimeError("Worker CTMC configuration was not initialized")
    config = _WORKER_CONFIG
    rng = _channel_rng(
        config.seed,
        energy_index,
        charge,
        impact_index,
        channel_index,
        trajectory_start,
    )

    primary_events = 0
    secondary_events = 0
    failures = 0
    successes = 0
    maximum_energy_drift = 0.0

    if channel_index < LOSS_CHANNEL_INDEX:
        orbital = WATER_ORBITALS[channel_index]
        bound_to = "target"
        binding_eV = orbital.binding_eV
    elif channel_index == LOSS_CHANNEL_INDEX:
        orbital = PROJECTILE_OUTER_ORBITAL.get(int(charge))
        if orbital is None:
            raise RuntimeError(
                f"Invalid projectile-loss task for charge state {charge}"
            )
        bound_to = "projectile"
        binding_eV = orbital.binding_eV
    else:
        raise RuntimeError(f"Invalid CTMC channel index {channel_index}")

    for trajectory_offset in range(trajectory_count):
        outcome, success, drift = simulate_one_trajectory(
            energy_keV_u=energy,
            charge_state=charge,
            impact_parameter_au=impact,
            bound_to=bound_to,
            binding_eV=binding_eV,
            start_separation_au=start_separation_au,
            minimum_integration_time_au=minimum_integration_time_au,
            config=config,
            rng=rng,
        )
        if not success:
            if config.max_failure_fraction == 0.0:
                raise TrajectoryIntegrationFailure(
                    {
                        "energy_index": int(energy_index),
                        "energy_keV_u": float(energy),
                        "charge_index": int(charge_index),
                        "charge_state": int(charge),
                        "impact_index": int(impact_index),
                        "impact_parameter_au": float(impact),
                        "channel_index": int(channel_index),
                        "trajectory_index": int(
                            trajectory_start + trajectory_offset
                        ),
                        "failure_outcome": outcome,
                        "relative_total_energy_drift": float(drift),
                        "rtol": float(config.rtol),
                        "atol": float(config.atol),
                    }
                )
            failures += 1
            continue
        successes += 1
        maximum_energy_drift = max(maximum_energy_drift, drift)
        primary_events += int(outcome == "ionized")
        if channel_index < LOSS_CHANNEL_INDEX:
            secondary_events += int(outcome == "captured_projectile")

    return (
        energy_index,
        charge_index,
        impact_index,
        channel_index,
        trajectory_start,
        trajectory_count,
        primary_events,
        secondary_events,
        failures,
        successes,
        maximum_energy_drift,
    )


