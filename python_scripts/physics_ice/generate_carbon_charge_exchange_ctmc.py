def effective_charge_and_derivative(
    core: CorePotential, radius_au: float
) -> tuple[float, float]:
    """Return Z_eff(r) and dZ_eff/dr for equations (6)-(9)."""
    r = max(float(radius_au), np.finfo(float).tiny)
    z = float(core.nuclear_charge)
    n = float(core.spectators)
    if core.spectators == 0:
        return z, 0.0

    exponent = core.zeta * r
    if exponent > 700.0:
        return z - n, 0.0

    exp_term = math.exp(exponent)
    ratio = core.eta / core.zeta
    denominator = 1.0 + ratio * (exp_term - 1.0)
    omega = 1.0 / denominator
    domega_dr = -core.eta * exp_term / (denominator * denominator)
    return z - n + n * omega, n * domega_dr


def potential_magnitude(core: CorePotential, radius_au: float) -> float:
    """Positive Z_eff(r)/r used in the electron binding potential."""
    r = max(float(radius_au), np.finfo(float).tiny)
    zeff, _ = effective_charge_and_derivative(core, r)
    return zeff / r


def _pair_force_on_first(
    displacement: np.ndarray,
    charge_first: float,
    derivative_first: float,
    charge_second: float,
    derivative_second: float,
    minimum_radius_au: float,
) -> np.ndarray:
    """
    Force on particle one for U(r) = Q1(r) Q2(r) / r.

    displacement is r1-r2. The opposite force acts on particle two.
    """
    radius = max(float(np.linalg.norm(displacement)), minimum_radius_au)
    unit = displacement / radius
    product = charge_first * charge_second
    dpotential_dr = (
        derivative_first * charge_second
        + charge_first * derivative_second
    ) / radius - product / (radius * radius)
    return -dpotential_dr * unit


def _three_body_rhs(
    _: float,
    state: np.ndarray,
    target_core: CorePotential,
    projectile_core: CorePotential,
    minimum_radius_au: float,
) -> np.ndarray:
    positions = state[:9].reshape(3, 3)
    velocities = state[9:].reshape(3, 3)
    forces = np.zeros((3, 3), dtype=float)

    # Particle order: target core, projectile core, active electron.
    target_position, projectile_position, electron_position = positions

    # Target-projectile interaction.
    d_tp = target_position - projectile_position
    r_tp = max(float(np.linalg.norm(d_tp)), minimum_radius_au)
    zt, dzt = effective_charge_and_derivative(target_core, r_tp)
    zp, dzp = effective_charge_and_derivative(projectile_core, r_tp)
    force = _pair_force_on_first(
        d_tp, zt, dzt, zp, dzp, minimum_radius_au
    )
    forces[0] += force
    forces[1] -= force

    # Target-electron interaction.
    d_te = target_position - electron_position
    r_te = max(float(np.linalg.norm(d_te)), minimum_radius_au)
    zt, dzt = effective_charge_and_derivative(target_core, r_te)
    force = _pair_force_on_first(
        d_te, zt, dzt, -1.0, 0.0, minimum_radius_au
    )
    forces[0] += force
    forces[2] -= force

    # Projectile-electron interaction.
    d_pe = projectile_position - electron_position
    r_pe = max(float(np.linalg.norm(d_pe)), minimum_radius_au)
    zp, dzp = effective_charge_and_derivative(projectile_core, r_pe)
    force = _pair_force_on_first(
        d_pe, zp, dzp, -1.0, 0.0, minimum_radius_au
    )
    forces[1] += force
    forces[2] -= force

    accelerations = forces / np.array(
        [WATER_MASS_AU, CARBON_MASS_AU, ELECTRON_MASS_AU],
        dtype=float,
    )[:, None]

    derivative = np.empty_like(state)
    derivative[:9] = velocities.reshape(-1)
    derivative[9:] = accelerations.reshape(-1)
    return derivative


def _pair_potential_energy(
    displacement: np.ndarray,
    first: CorePotential | None,
    second: CorePotential | None,
    minimum_radius_au: float,
) -> float:
    radius = max(float(np.linalg.norm(displacement)), minimum_radius_au)
    if first is None:
        q_first = -1.0
    else:
        q_first, _ = effective_charge_and_derivative(first, radius)
    if second is None:
        q_second = -1.0
    else:
        q_second, _ = effective_charge_and_derivative(second, radius)
    return q_first * q_second / radius


def total_three_body_energy(
    state: np.ndarray,
    target_core: CorePotential,
    projectile_core: CorePotential,
    minimum_radius_au: float,
) -> float:
    positions = state[:9].reshape(3, 3)
    velocities = state[9:].reshape(3, 3)
    masses = np.array(
        [WATER_MASS_AU, CARBON_MASS_AU, ELECTRON_MASS_AU],
        dtype=float,
    )
    kinetic = 0.5 * np.sum(masses[:, None] * velocities * velocities)
    potential = _pair_potential_energy(
        positions[0] - positions[1],
        target_core,
        projectile_core,
        minimum_radius_au,
    )
    potential += _pair_potential_energy(
        positions[0] - positions[2],
        target_core,
        None,
        minimum_radius_au,
    )
    potential += _pair_potential_energy(
        positions[1] - positions[2],
        projectile_core,
        None,
        minimum_radius_au,
    )
    return float(kinetic + potential)


def _state_to_relative_coordinates(state: np.ndarray) -> np.ndarray:
    """Convert the 18 Cartesian variables to the paper's 12 relative ones."""
    positions = state[:9].reshape(3, 3)
    velocities = state[9:].reshape(3, 3)
    relative = np.empty(12, dtype=float)
    relative[:3] = positions[1] - positions[0]
    relative[3:6] = positions[2] - positions[0]
    relative[6:9] = velocities[1] - velocities[0]
    relative[9:12] = velocities[2] - velocities[0]
    return relative


def _relative_to_state(relative: np.ndarray) -> np.ndarray:
    """Construct an equivalent Cartesian state in the instantaneous target frame."""
    state = np.zeros(18, dtype=float)
    state[3:6] = relative[:3]
    state[6:9] = relative[3:6]
    state[12:15] = relative[6:9]
    state[15:18] = relative[9:12]
    return state


def relative_three_body_energy(
    relative: np.ndarray,
    target_core: CorePotential,
    projectile_core: CorePotential,
    minimum_radius_au: float,
) -> float:
    """Internal energy computed from relative coordinates with COM removed."""
    r_projectile = relative[:3]
    r_electron = relative[3:6]
    v_projectile = relative[6:9]
    v_electron = relative[9:12]

    total_mass = WATER_MASS_AU + CARBON_MASS_AU + ELECTRON_MASS_AU
    center_of_mass_velocity = (
        CARBON_MASS_AU * v_projectile
        + ELECTRON_MASS_AU * v_electron
    ) / total_mass
    target_velocity_com = -center_of_mass_velocity
    projectile_velocity_com = v_projectile - center_of_mass_velocity
    electron_velocity_com = v_electron - center_of_mass_velocity
    kinetic = 0.5 * (
        WATER_MASS_AU * np.dot(target_velocity_com, target_velocity_com)
        + CARBON_MASS_AU
        * np.dot(projectile_velocity_com, projectile_velocity_com)
        + ELECTRON_MASS_AU
        * np.dot(electron_velocity_com, electron_velocity_com)
    )

    potential = _pair_potential_energy(
        -r_projectile,
        target_core,
        projectile_core,
        minimum_radius_au,
    )
    potential += _pair_potential_energy(
        -r_electron,
        target_core,
        None,
        minimum_radius_au,
    )
    potential += _pair_potential_energy(
        r_projectile - r_electron,
        projectile_core,
        None,
        minimum_radius_au,
    )
    return float(kinetic + potential)


