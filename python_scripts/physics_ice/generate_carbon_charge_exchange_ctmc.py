def validate_args(args: argparse.Namespace) -> None:
    if args.energy_min_kev_u <= 0.0:
        raise ValueError("--energy-min-kev-u must be positive")
    if args.energy_max_kev_u <= args.energy_min_kev_u:
        raise ValueError("--energy-max-kev-u must exceed the minimum")
    if args.charge_step < 1:
        raise ValueError("--charge-step must be a positive integer")
    if args.impact_points < 2:
        raise ValueError("--impact-points must be at least two")
    if args.trajectories < 1:
        raise ValueError("--trajectories must be positive")
    if args.workers < 1:
        raise ValueError("--workers must be positive")
    if args.backend == "numba" and integrate_relative_dop853 is None:
        raise ValueError(
            "The Numba backend is unavailable: "
            f"{_NUMBA_IMPORT_ERROR!s}. Use --backend scipy or install numba."
        )
    if args.maximum_integration_steps < 1:
        raise ValueError("--maximum-integration-steps must be positive")
    if args.progress_interval < 1:
        raise ValueError("--progress-interval must be positive")
    if args.radial_grid_points < 128:
        raise ValueError("--radial-grid-points must be at least 128")
    if args.loss_bmax_au <= 0.0:
        raise ValueError("--loss-bmax-au must be positive")
    if args.start_separation_au is not None and args.start_separation_au <= 0:
        raise ValueError("--start-separation-au must be positive")
    if args.rtol <= 0.0 or args.atol <= 0.0:
        raise ValueError("Integrator tolerances must be positive")
    if args.minimum_radius_au <= 0.0:
        raise ValueError("--minimum-radius-au must be positive")
    if not (0.0 <= args.max_failure_fraction < 1.0):
        raise ValueError("--max-failure-fraction must lie in [0,1)")
    if args.checkpoint_every < 1:
        raise ValueError("--checkpoint-every must be positive")


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        validate_args(args)
        energies = build_energy_grid(args)
        charges = parse_charges(args.charges, args.charge_step)
        target_bmax = parse_target_bmax(args.target_bmax_au)
    except ValueError as exc:
        parser.error(str(exc))

    maximum_b = max(max(target_bmax), args.loss_bmax_au)
    impact_au = np.linspace(0.0, maximum_b, args.impact_points)
    config = CTMCConfig(
        backend=str(args.backend),
        trajectories=int(args.trajectories),
        target_bmax_au=target_bmax,
        loss_bmax_au=float(args.loss_bmax_au),
        radial_grid_points=int(args.radial_grid_points),
        start_separation_au=(
            None
            if args.start_separation_au is None
            else float(args.start_separation_au)
        ),
        rtol=float(args.rtol),
        atol=float(args.atol),
        max_step_au=float(args.max_step_au),
        minimum_radius_au=float(args.minimum_radius_au),
        max_failure_fraction=float(args.max_failure_fraction),
        maximum_integration_steps=int(args.maximum_integration_steps),
        seed=int(args.seed),
    )

    shape = (energies.size, charges.size, impact_au.size)
    pi = np.full(shape + (len(WATER_ORBITALS),), np.nan, dtype=float)
    pc = np.full_like(pi, np.nan)
    pl = np.full(shape, np.nan, dtype=float)
    done = np.zeros(shape, dtype=bool)
    failures = np.zeros(shape, dtype=np.int64)
    successes = np.zeros(shape, dtype=np.int64)
    maximum_energy_drift = np.zeros(shape, dtype=float)

    signature = configuration_signature(
        energies, charges, impact_au, config
    )
    checkpoint_path = (
        args.output_dir / "carbon_charge_exchange_ctmc_checkpoint.npz"
    )
    if not args.no_resume:
        checkpoint = load_checkpoint(checkpoint_path, signature)
        if checkpoint is not None:
            pi[...] = checkpoint["pi"]
            pc[...] = checkpoint["pc"]
            pl[...] = checkpoint["pl"]
            done[...] = checkpoint["done"]
            failures[...] = checkpoint["failures"]
            successes[...] = checkpoint["successes"]
            maximum_energy_drift[...] = checkpoint["maximum_energy_drift"]
            print(
                f"Resumed {int(np.sum(done))}/{done.size} probability points "
                f"from {checkpoint_path}"
            )

    pending_points = int(done.size - np.count_nonzero(done))
    estimated = estimate_trajectory_count(
        iter_pending_probability_tasks(energies, charges, impact_au, done),
        config,
    )
    print(
        f"Grid: {energies.size} energies x {charges.size} charge states x "
        f"{impact_au.size} impact parameters"
    )
    print(
        f"Pending probability points: {pending_points:,}; "
        f"estimated trajectories: {estimated:,}"
    )
    print(f"Backend: {config.backend}; workers: {args.workers}")
    if args.dry_run:
        return 0

    if config.backend == "numba":
        assert warm_up_numba_backend is not None
        print("Compiling/loading the Numba DOP853 kernel...")
        warm_up_numba_backend()

    def store_result(
        result: tuple[
            int, int, int, np.ndarray, np.ndarray, float, int, int, float
        ]
    ) -> None:
        (
            energy_index,
            charge_index,
            impact_index,
            point_pi,
            point_pc,
            point_pl,
            point_failures,
            point_successes,
            point_maximum_drift,
        ) = result
        pi[energy_index, charge_index, impact_index] = point_pi
        pc[energy_index, charge_index, impact_index] = point_pc
        pl[energy_index, charge_index, impact_index] = point_pl
        failures[energy_index, charge_index, impact_index] = point_failures
        successes[energy_index, charge_index, impact_index] = point_successes
        maximum_energy_drift[
            energy_index, charge_index, impact_index
        ] = point_maximum_drift
        done[energy_index, charge_index, impact_index] = True

    process_context = multiprocessing.get_context()
    trajectory_counter = process_context.Value("Q", 0)
    stop_progress = threading.Event()
    trajectory_progress = tqdm(
        total=estimated,
        desc="Trajectories",
        unit="traj",
        unit_scale=True,
        dynamic_ncols=True,
        position=0,
    )
    point_progress = tqdm(
        total=pending_points,
        desc="Grid points",
        unit="point",
        dynamic_ncols=True,
        position=1,
    )

    def monitor_trajectory_progress() -> None:
        displayed = 0
        while not stop_progress.wait(0.5):
            with trajectory_counter.get_lock():
                completed = int(trajectory_counter.value)
            if completed > displayed:
                trajectory_progress.update(completed - displayed)
                displayed = completed
        with trajectory_counter.get_lock():
            completed = int(trajectory_counter.value)
        if completed > displayed:
            trajectory_progress.update(completed - displayed)

    progress_thread = threading.Thread(
        target=monitor_trajectory_progress,
        name="ctmc-tqdm-monitor",
        daemon=True,
    )
    progress_thread.start()

    completed_since_checkpoint = 0
    try:
        try:
            if args.workers == 1:
                _init_worker(
                    config,
                    trajectory_counter,
                    args.progress_interval,
                )
                iterator: Iterable[
                    tuple[
                        int,
                        int,
                        int,
                        np.ndarray,
                        np.ndarray,
                        float,
                        int,
                        int,
                        float,
                    ]
                ] = map(
                    _compute_probability_point,
                    iter_pending_probability_tasks(
                        energies, charges, impact_au, done
                    ),
                )
                for result in iterator:
                    store_result(result)
                    point_progress.update(1)
                    completed_since_checkpoint += 1
                    if completed_since_checkpoint >= args.checkpoint_every:
                        save_checkpoint(
                            checkpoint_path,
                            signature=signature,
                            energies=energies,
                            charges=charges,
                            impact_au=impact_au,
                            pi=pi,
                            pc=pc,
                            pl=pl,
                            done=done,
                            failures=failures,
                            successes=successes,
                            maximum_energy_drift=maximum_energy_drift,
                        )
                        completed_since_checkpoint = 0
            else:
                with ProcessPoolExecutor(
                    max_workers=args.workers,
                    initializer=_init_worker,
                    initargs=(
                        config,
                        trajectory_counter,
                        args.progress_interval,
                    ),
                    mp_context=process_context,
                ) as executor:
                    results = bounded_parallel_results(
                        executor,
                        iter_pending_probability_tasks(
                            energies, charges, impact_au, done
                        ),
                        maximum_pending=max(2 * args.workers, 1),
                    )
                    for result in results:
                        store_result(result)
                        point_progress.update(1)
                        completed_since_checkpoint += 1
                        if (
                            completed_since_checkpoint
                            >= args.checkpoint_every
                        ):
                            save_checkpoint(
                                checkpoint_path,
                                signature=signature,
                                energies=energies,
                                charges=charges,
                                impact_au=impact_au,
                                pi=pi,
                                pc=pc,
                                pl=pl,
                                done=done,
                                failures=failures,
                                successes=successes,
                                maximum_energy_drift=maximum_energy_drift,
                            )
                            completed_since_checkpoint = 0
        finally:
            if np.any(done):
                save_checkpoint(
                    checkpoint_path,
                    signature=signature,
                    energies=energies,
                    charges=charges,
                    impact_au=impact_au,
                    pi=pi,
                    pc=pc,
                    pl=pl,
                    done=done,
                    failures=failures,
                    successes=successes,
                    maximum_energy_drift=maximum_energy_drift,
                )
    finally:
        stop_progress.set()
        progress_thread.join()
        point_progress.close()
        trajectory_progress.close()

    if not np.all(done):
        raise RuntimeError("CTMC grid is incomplete; checkpoint was preserved")

    paths = write_outputs(
        args.output_dir,
        energies=energies,
        charges=charges,
        impact_au=impact_au,
        pi=pi,
        pc=pc,
        pl=pl,
        failures=failures,
        successes=successes,
        maximum_energy_drift=maximum_energy_drift,
        config=config,
        workers=args.workers,
        signature=signature,
    )
    print("Wrote:")
    for path in paths:
        print(f"  {path}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        print("\nInterrupted; the CTMC checkpoint was preserved.", file=sys.stderr)
        raise SystemExit(130)
