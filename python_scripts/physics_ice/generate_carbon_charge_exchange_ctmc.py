def parse_float_list(text: str) -> np.ndarray:
    values = [float(item.strip()) for item in text.split(",") if item.strip()]
    if not values:
        raise argparse.ArgumentTypeError("Expected at least one numeric value")
    values = sorted(set(values))
    if values[0] <= 0.0:
        raise argparse.ArgumentTypeError("Energies must be positive")
    return np.asarray(values, dtype=float)


def parse_charges(text: str, charge_step: int) -> np.ndarray:
    cleaned = text.strip()
    if ":" in cleaned:
        parts = [part.strip() for part in cleaned.split(":")]
        if len(parts) != 2:
            raise ValueError("Charge range must have form qmin:qmax")
        qmin, qmax = map(int, parts)
        charges = np.arange(qmin, qmax + 1, charge_step, dtype=int)
    else:
        charges = np.asarray(
            sorted(set(int(part.strip()) for part in cleaned.split(",") if part.strip())),
            dtype=int,
        )
    if charges.size == 0:
        raise ValueError("No charge states selected")
    if np.any((charges < 0) | (charges > 6)):
        raise ValueError("Carbon charge states must lie in 0,...,6")
    return charges


def build_energy_grid(args: argparse.Namespace) -> np.ndarray:
    if args.energies is not None:
        return parse_float_list(args.energies)
    if args.energy_step_kev_u is not None:
        step = float(args.energy_step_kev_u)
        if step <= 0.0:
            raise ValueError("--energy-step-kev-u must be positive")
        count = int(
            math.floor(
                (args.energy_max_kev_u - args.energy_min_kev_u) / step
            )
        )
        grid = args.energy_min_kev_u + step * np.arange(count + 1)
        if grid[-1] < args.energy_max_kev_u * (1.0 - 1.0e-12):
            grid = np.append(grid, args.energy_max_kev_u)
        return np.asarray(grid, dtype=float)
    if args.energy_points < 2:
        raise ValueError("--energy-points must be at least two")
    if args.energy_spacing == "linear":
        return np.linspace(
            args.energy_min_kev_u,
            args.energy_max_kev_u,
            args.energy_points,
        )
    return np.geomspace(
        args.energy_min_kev_u,
        args.energy_max_kev_u,
        args.energy_points,
    )


def configuration_signature(
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    config: CTMCConfig,
) -> str:
    config_payload = asdict(config)
    if not np.isfinite(config_payload["max_step_au"]):
        config_payload["max_step_au"] = None
    payload = {
        "energies": energies.tolist(),
        "charges": charges.tolist(),
        "impact_au": impact_au.tolist(),
        "config": config_payload,
        "model_version": 1,
    }
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(encoded).hexdigest()


def save_checkpoint(
    path: Path,
    *,
    signature: str,
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    pi: np.ndarray,
    pc: np.ndarray,
    pl: np.ndarray,
    done: np.ndarray,
    failures: np.ndarray,
    successes: np.ndarray,
    maximum_energy_drift: np.ndarray,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(".tmp.npz")
    np.savez_compressed(
        temporary,
        signature=np.asarray(signature),
        energies_keV_u=energies,
        charges=charges,
        impact_au=impact_au,
        pi=pi,
        pc=pc,
        pl=pl,
        done=done,
        failures=failures,
        successes=successes,
        maximum_energy_drift=maximum_energy_drift,
    )
    os.replace(temporary, path)


def load_checkpoint(
    path: Path,
    expected_signature: str,
) -> dict[str, np.ndarray] | None:
    if not path.exists():
        return None
    with np.load(path, allow_pickle=False) as data:
        signature = str(np.asarray(data["signature"]).item())
        if signature != expected_signature:
            raise RuntimeError(
                f"Checkpoint {path} belongs to a different configuration. "
                "Use a new output directory or remove the checkpoint."
            )
        return {key: np.asarray(data[key]) for key in data.files}


def write_outputs(
    output_dir: Path,
    *,
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    pi: np.ndarray,
    pc: np.ndarray,
    pl: np.ndarray,
    failures: np.ndarray,
    successes: np.ndarray,
    maximum_energy_drift: np.ndarray,
    config: CTMCConfig,
    workers: int,
    signature: str,
) -> tuple[Path, Path, Path, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    rows, columns = build_cross_section_rows(
        energies, charges, impact_au, pi, pc, pl
    )

    dat_path = output_dir / "carbon_charge_exchange_h2o.dat"
    csv_path = output_dir / "carbon_charge_exchange_h2o.csv"
    probabilities_path = (
        output_dir / "carbon_charge_exchange_probabilities.npz"
    )
    metadata_path = output_dir / "carbon_charge_exchange_metadata.json"

    dat_header = (
        " ".join(columns)
        + "\nMicroscopic cross sections in cm2 per H2O molecule; "
        "E is projectile energy in keV/u."
    )
    np.savetxt(
        dat_path,
        rows,
        fmt=["%.9E", "%.0f"] + ["%.9E"] * (rows.shape[1] - 2),
        header=dat_header,
        comments="# ",
    )
    np.savetxt(
        csv_path,
        rows,
        delimiter=",",
        fmt=["%.9E", "%.0f"] + ["%.9E"] * (rows.shape[1] - 2),
        header=",".join(columns),
        comments="",
    )
    np.savez_compressed(
        probabilities_path,
        energies_keV_u=energies,
        charges=charges,
        impact_au=impact_au,
        orbital_labels=np.asarray([o.label for o in WATER_ORBITALS]),
        pi=pi,
        pc=pc,
        pl=pl,
        failures=failures,
        successes=successes,
        maximum_energy_drift=maximum_energy_drift,
    )

    attempted = int(np.sum(failures) + np.sum(successes))
    config_metadata = asdict(config)
    if not np.isfinite(config_metadata["max_step_au"]):
        config_metadata["max_step_au"] = None
    metadata = {
        "model": "Liamsuwan-Nikjoo three-body CTMC with IEVM/IPM",
        "doi": "10.1088/0031-9155/58/3/641",
        "target": "isolated spherical H2O pseudotarget",
        "density_applied": False,
        "cross_section_unit": "cm2 per H2O molecule",
        "energy_unit": "keV/u",
        "charge_states": charges.tolist(),
        "configuration_signature": signature,
        "workers": int(workers),
        "ctmc_config": config_metadata,
        "water_orbitals": [asdict(orbital) for orbital in WATER_ORBITALS],
        "carbon_outer_orbitals": {
            str(q): asdict(orbital)
            for q, orbital in CARBON_OUTER_ORBITAL.items()
        },
        "trajectory_statistics": {
            "attempted": attempted,
            "successful": int(np.sum(successes)),
            "failed": int(np.sum(failures)),
            "failure_fraction": (
                float(np.sum(failures) / attempted) if attempted else 0.0
            ),
            "maximum_relative_total_energy_drift": float(
                np.max(maximum_energy_drift)
            ),
        },
        "notes": [
            "q is discrete carbon charge, not dielectric momentum transfer.",
            "No ELF or condensed-phase correction is used.",
            "Ice density must be applied in Geant4 as n_H2O*sigma.",
            "The paper does not tabulate exact per-orbital bmax values; "
            "the conservative default uses 25 a.u. for every H2O orbital.",
            "The automatic initial separation smoothly spans the paper's "
            "stated 10000-to-1000 a.u. range and must be convergence-tested.",
            "The capture inequality in the paper prose is reversed relative "
            "to its E_et/E_ep definitions; this code uses the physical "
            "projectile-bound condition E_ep<=0 and E_et>0.",
            "Modified-IEVM shell sums are retained exactly as published and "
            "are not ad-hoc clipped if their approximate channel weights "
            "exceed one at very small impact parameter.",
        ],
    }
    metadata_path.write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return dat_path, csv_path, probabilities_path, metadata_path


def iter_pending_probability_tasks(
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    done: np.ndarray,
) -> Iterable[tuple[int, int, float, int, int, float]]:
    """Yield unfinished points fast-energy-first without materializing a list."""
    # High-energy trajectories have shorter physical time intervals. Completing
    # them first produces early checkpoints without changing any task seed or
    # the final table ordering.
    for energy_index in range(energies.size - 1, -1, -1):
        energy = energies[energy_index]
        for charge_index, charge in enumerate(charges):
            for impact_index, impact in enumerate(impact_au):
                if not done[energy_index, charge_index, impact_index]:
                    yield (
                        energy_index,
                        charge_index,
                        float(energy),
                        int(charge),
                        impact_index,
                        float(impact),
                    )


def estimate_trajectory_count(
    tasks: Iterable[tuple[int, int, float, int, int, float]],
    config: CTMCConfig,
) -> int:
    count = 0
    for _, _, _, charge, _, impact in tasks:
        active_target_shells = sum(
            impact <= bmax for bmax in config.target_bmax_au
        )
        loss_active = charge <= 5 and impact <= config.loss_bmax_au
        count += config.trajectories * (
            active_target_shells + int(loss_active)
        )
    return int(count)


def bounded_parallel_results(
    executor: ProcessPoolExecutor,
    tasks: Iterable[tuple[int, int, float, int, int, float]],
    maximum_pending: int,
) -> Iterable[
    tuple[int, int, int, np.ndarray, np.ndarray, float, int, int, float]
]:
    """Submit a bounded number of futures instead of all grid points at once."""
    task_iterator = iter(tasks)
    pending = set()
    for _ in range(maximum_pending):
        try:
            task = next(task_iterator)
        except StopIteration:
            break
        pending.add(executor.submit(_compute_probability_point, task))

    while pending:
        completed, pending = wait(pending, return_when=FIRST_COMPLETED)
        for future in completed:
            yield future.result()
            try:
                task = next(task_iterator)
            except StopIteration:
                continue
            pending.add(executor.submit(_compute_probability_point, task))


def parse_target_bmax(text: str) -> tuple[float, ...]:
    values = tuple(
        float(part.strip()) for part in text.split(",") if part.strip()
    )
    if len(values) == 1:
        values = values * len(WATER_ORBITALS)
    if len(values) != len(WATER_ORBITALS):
        raise ValueError(
            "--target-bmax-au requires one value or five comma-separated "
            "values ordered as 1b1,3a1,1b2,2a1,1a1"
        )
    if any(value <= 0.0 for value in values):
        raise ValueError("All target bmax values must be positive")
    return values


