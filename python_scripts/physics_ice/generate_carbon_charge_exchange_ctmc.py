def projectile_velocity_au(energy_keV_u: float) -> float:
    energy_ha_per_u = float(energy_keV_u) * KEV_TO_HARTREE
    return math.sqrt(2.0 * energy_ha_per_u / U_TO_ELECTRON_MASS)


def automatic_start_separation_au(energy_keV_u: float) -> float:
    """
    Interpolate the paper's stated 10^4-to-10^3 a.u. separation range.

    The precise per-energy values were not tabulated. This smooth rule reaches
    10,000 a.u. at 1 keV/u and 1,000 a.u. at 10^4 keV/u. Convergence must be
    checked by rerunning with --start-separation-au.
    """
    energy = max(float(energy_keV_u), 1.0)
    separation = 1.0e4 * energy ** (-0.25)
    return float(np.clip(separation, 1.0e3, 1.0e4))


def _electron_core_energy(
    final_state: np.ndarray,
    core_index: int,
    core: CorePotential,
    core_mass_au: float,
    minimum_radius_au: float,
) -> float:
    positions = final_state[:9].reshape(3, 3)
    velocities = final_state[9:].reshape(3, 3)
    relative_position = positions[2] - positions[core_index]
    relative_velocity = velocities[2] - velocities[core_index]
    radius = max(float(np.linalg.norm(relative_position)), minimum_radius_au)
    reduced_mass = (
        ELECTRON_MASS_AU
        * core_mass_au
        / (ELECTRON_MASS_AU + core_mass_au)
    )
    return float(
        0.5 * reduced_mass * np.dot(relative_velocity, relative_velocity)
        - potential_magnitude(core, radius)
    )


def _build_initial_state(
    *,
    energy_keV_u: float,
    impact_parameter_au: float,
    separation_au: float,
    bound_to: str,
    binding_eV: float,
    target_core: CorePotential,
    projectile_core: CorePotential,
    radial_grid_points: int,
    rng: np.random.Generator,
) -> np.ndarray:
    velocity = projectile_velocity_au(energy_keV_u)
    target_position = np.zeros(3, dtype=float)
    projectile_position = np.array(
        [impact_parameter_au, 0.0, -separation_au],
        dtype=float,
    )
    target_velocity = np.zeros(3, dtype=float)
    projectile_velocity = np.array([0.0, 0.0, velocity], dtype=float)

    if bound_to == "target":
        electron_position, electron_velocity = sample_bound_electron(
            target_core,
            WATER_MASS_AU,
            binding_eV,
            target_position,
            target_velocity,
            radial_grid_points,
            rng,
        )
    elif bound_to == "projectile":
        electron_position, electron_velocity = sample_bound_electron(
            projectile_core,
            CARBON_MASS_AU,
            binding_eV,
            projectile_position,
            projectile_velocity,
            radial_grid_points,
            rng,
        )
    else:
        raise ValueError("bound_to must be 'target' or 'projectile'")

    state = np.empty(18, dtype=float)
    state[:9] = np.vstack(
        (target_position, projectile_position, electron_position)
    ).reshape(-1)
    state[9:] = np.vstack(
        (target_velocity, projectile_velocity, electron_velocity)
    ).reshape(-1)
    return state


def simulate_one_trajectory(
    *,
    energy_keV_u: float,
    charge_state: int,
    impact_parameter_au: float,
    bound_to: str,
    binding_eV: float,
    config: CTMCConfig,
    rng: np.random.Generator,
) -> tuple[str, bool, float]:
    """
    Return (outcome, success, relative total-energy drift).

    Outcomes are "ionized", "captured_projectile", "retained_target", and
    "ambiguous_bound". In the target-electron scheme, capture means the
    physically required E_ep <= 0 and E_et > 0. The inequality printed for
    capture in the paper's prose is reversed relative to the definitions of
    E_et and E_ep and would classify an electron retained by H2O as captured.
    """
    q = int(charge_state)
    if bound_to == "target":
        target_core = CorePotential.from_zn(
            WATER_PSEUDO_NUCLEAR_CHARGE, 9
        )
        projectile_core = CorePotential.from_zn(
            CARBON_NUCLEAR_CHARGE, CARBON_NUCLEAR_CHARGE - q
        )
    elif bound_to == "projectile":
        if q not in CARBON_OUTER_ORBITAL:
            return "retained_target", True, 0.0
        target_core = CorePotential.from_zn(
            WATER_PSEUDO_NUCLEAR_CHARGE, 10
        )
        # One projectile electron is active, so it is excluded from N.
        projectile_core = CorePotential.from_zn(
            CARBON_NUCLEAR_CHARGE, CARBON_NUCLEAR_CHARGE - q - 1
        )
    else:
        raise ValueError("bound_to must be 'target' or 'projectile'")

    separation = (
        automatic_start_separation_au(energy_keV_u)
        if config.start_separation_au is None
        else config.start_separation_au
    )
    initial_state = _build_initial_state(
        energy_keV_u=energy_keV_u,
        impact_parameter_au=impact_parameter_au,
        separation_au=separation,
        bound_to=bound_to,
        binding_eV=binding_eV,
        target_core=target_core,
        projectile_core=projectile_core,
        radial_grid_points=config.radial_grid_points,
        rng=rng,
    )
    velocity = projectile_velocity_au(energy_keV_u)
    end_time = 2.0 * separation / velocity
    initial_relative = _state_to_relative_coordinates(initial_state)
    initial_energy = relative_three_body_energy(
        initial_relative,
        target_core,
        projectile_core,
        config.minimum_radius_au,
    )

    if config.backend == "numba":
        if integrate_relative_dop853 is None:
            raise RuntimeError(
                "The Numba backend was requested but could not be imported"
            ) from _NUMBA_IMPORT_ERROR
        success, final_relative, _, _ = integrate_relative_dop853(
            initial_relative,
            end_time,
            _core_parameters(target_core),
            _core_parameters(projectile_core),
            config.rtol,
            config.atol,
            config.max_step_au,
            config.minimum_radius_au,
            WATER_MASS_AU,
            CARBON_MASS_AU,
            config.maximum_integration_steps,
        )
        if not success or not np.all(np.isfinite(final_relative)):
            return "integration_failure", False, math.inf
        final_state = _relative_to_state(final_relative)
    elif config.backend == "scipy":
        max_step = (
            np.inf if not np.isfinite(config.max_step_au)
            else config.max_step_au
        )
        solution = solve_ivp(
            _three_body_rhs,
            (0.0, end_time),
            initial_state,
            method="DOP853",
            t_eval=(end_time,),
            args=(target_core, projectile_core, config.minimum_radius_au),
            rtol=config.rtol,
            atol=config.atol,
            max_step=max_step,
        )
        if not solution.success or solution.y.shape[1] == 0:
            return "integration_failure", False, math.inf
        final_state = solution.y[:, -1]
        if not np.all(np.isfinite(final_state)):
            return "integration_failure", False, math.inf
        final_relative = _state_to_relative_coordinates(final_state)
    else:  # Defensive: CLI validation should make this unreachable.
        raise ValueError(f"Unknown CTMC backend: {config.backend!r}")

    final_energy = relative_three_body_energy(
        final_relative,
        target_core,
        projectile_core,
        config.minimum_radius_au,
    )
    energy_drift = abs(final_energy - initial_energy) / max(
        abs(initial_energy), 1.0
    )

    energy_target = _electron_core_energy(
        final_state,
        0,
        target_core,
        WATER_MASS_AU,
        config.minimum_radius_au,
    )
    energy_projectile = _electron_core_energy(
        final_state,
        1,
        projectile_core,
        CARBON_MASS_AU,
        config.minimum_radius_au,
    )

    if energy_target > 0.0 and energy_projectile > 0.0:
        outcome = "ionized"
    elif energy_projectile <= 0.0 and energy_target > 0.0:
        outcome = "captured_projectile"
    elif energy_target <= 0.0 and energy_projectile > 0.0:
        outcome = "retained_target"
    else:
        # At a converged final separation this should be negligible. Assign to
        # the more strongly bound center, while retaining a diagnostic label.
        if energy_projectile < energy_target:
            outcome = "captured_projectile"
        else:
            outcome = "ambiguous_bound"

    return outcome, True, float(energy_drift)


def _simulate_target_orbital(
    energy_keV_u: float,
    charge_state: int,
    impact_parameter_au: float,
    orbital: Orbital,
    config: CTMCConfig,
    rng: np.random.Generator,
) -> tuple[float, float, int, int, float]:
    ionized = 0
    captured = 0
    failures = 0
    successes = 0
    maximum_energy_drift = 0.0
    unreported_trajectories = 0
    for _ in range(config.trajectories):
        outcome, success, drift = simulate_one_trajectory(
            energy_keV_u=energy_keV_u,
            charge_state=charge_state,
            impact_parameter_au=impact_parameter_au,
            bound_to="target",
            binding_eV=orbital.binding_eV,
            config=config,
            rng=rng,
        )
        unreported_trajectories += 1
        if unreported_trajectories >= _WORKER_PROGRESS_INTERVAL:
            _advance_worker_progress(unreported_trajectories)
            unreported_trajectories = 0
        if not success:
            failures += 1
            continue
        successes += 1
        maximum_energy_drift = max(maximum_energy_drift, drift)
        ionized += int(outcome == "ionized")
        captured += int(outcome == "captured_projectile")
    _advance_worker_progress(unreported_trajectories)

    if successes == 0:
        raise RuntimeError(
            "All target-electron trajectories failed for "
            f"E={energy_keV_u:g} keV/u, q={charge_state}, "
            f"b={impact_parameter_au:g} a.u., orbital={orbital.label}"
        )
    return (
        ionized / successes,
        captured / successes,
        failures,
        successes,
        maximum_energy_drift,
    )


def _simulate_projectile_loss(
    energy_keV_u: float,
    charge_state: int,
    impact_parameter_au: float,
    config: CTMCConfig,
    rng: np.random.Generator,
) -> tuple[float, int, int, float]:
    orbital = CARBON_OUTER_ORBITAL.get(int(charge_state))
    if orbital is None:
        return 0.0, 0, 0, 0.0

    lost = 0
    failures = 0
    successes = 0
    maximum_energy_drift = 0.0
    unreported_trajectories = 0
    for _ in range(config.trajectories):
        outcome, success, drift = simulate_one_trajectory(
            energy_keV_u=energy_keV_u,
            charge_state=charge_state,
            impact_parameter_au=impact_parameter_au,
            bound_to="projectile",
            binding_eV=orbital.binding_eV,
            config=config,
            rng=rng,
        )
        unreported_trajectories += 1
        if unreported_trajectories >= _WORKER_PROGRESS_INTERVAL:
            _advance_worker_progress(unreported_trajectories)
            unreported_trajectories = 0
        if not success:
            failures += 1
            continue
        successes += 1
        maximum_energy_drift = max(maximum_energy_drift, drift)
        # Equation (paper prose below eq. 3): projectile ionization requires
        # the electron to be unbound from both centers.
        lost += int(outcome == "ionized")
    _advance_worker_progress(unreported_trajectories)

    if successes == 0:
        raise RuntimeError(
            "All projectile-electron trajectories failed for "
            f"E={energy_keV_u:g} keV/u, q={charge_state}, "
            f"b={impact_parameter_au:g} a.u."
        )
    return (
        lost / successes,
        failures,
        successes,
        maximum_energy_drift,
    )


# ---------------------------------------------------------------------------
# Parallel worker: one (energy, charge, impact parameter) point
# ---------------------------------------------------------------------------


def _init_worker(
    config: CTMCConfig,
    progress_counter=None,
    progress_interval: int = CARBON_CTMC_PROGRESS_INTERVAL,
) -> None:
    global _WORKER_CONFIG, _WORKER_PROGRESS_COUNTER
    global _WORKER_PROGRESS_INTERVAL
    _WORKER_CONFIG = config
    _WORKER_PROGRESS_COUNTER = progress_counter
    _WORKER_PROGRESS_INTERVAL = max(int(progress_interval), 1)


def _advance_worker_progress(trajectories: int) -> None:
    if trajectories <= 0 or _WORKER_PROGRESS_COUNTER is None:
        return
    with _WORKER_PROGRESS_COUNTER.get_lock():
        _WORKER_PROGRESS_COUNTER.value += int(trajectories)


def _seed_for_task(
    master_seed: int,
    energy_index: int,
    charge_state: int,
    impact_index: int,
) -> np.random.SeedSequence:
    return np.random.SeedSequence(
        [int(master_seed), int(energy_index), int(charge_state), int(impact_index)]
    )


def _compute_probability_point(
    task: tuple[int, int, float, int, int, float]
) -> tuple[int, int, int, np.ndarray, np.ndarray, float, int, int, float]:
    energy_index, charge_index, energy, charge, impact_index, impact = task
    if _WORKER_CONFIG is None:
        raise RuntimeError("Worker CTMC configuration was not initialized")
    config = _WORKER_CONFIG
    rng = np.random.default_rng(
        _seed_for_task(config.seed, energy_index, charge, impact_index)
    )

    pi = np.zeros(len(WATER_ORBITALS), dtype=float)
    pc = np.zeros(len(WATER_ORBITALS), dtype=float)
    failures = 0
    successes = 0
    maximum_energy_drift = 0.0

    for orbital_index, orbital in enumerate(WATER_ORBITALS):
        if impact > config.target_bmax_au[orbital_index]:
            continue
        result = _simulate_target_orbital(
            energy,
            charge,
            impact,
            orbital,
            config,
            rng,
        )
        pi[orbital_index], pc[orbital_index] = result[:2]
        failures += result[2]
        successes += result[3]
        maximum_energy_drift = max(maximum_energy_drift, result[4])

    pl = 0.0
    if charge <= 5 and impact <= config.loss_bmax_au:
        loss_result = _simulate_projectile_loss(
            energy,
            charge,
            impact,
            config,
            rng,
        )
        pl = loss_result[0]
        failures += loss_result[1]
        successes += loss_result[2]
        maximum_energy_drift = max(
            maximum_energy_drift, loss_result[3]
        )

    attempted = failures + successes
    if attempted and failures / attempted > config.max_failure_fraction:
        raise RuntimeError(
            f"Trajectory failure fraction {failures / attempted:.3%} exceeds "
            f"limit {config.max_failure_fraction:.3%} at "
            f"E={energy:g} keV/u, q={charge}, b={impact:g} a.u."
        )

    return (
        energy_index,
        charge_index,
        impact_index,
        pi,
        pc,
        pl,
        failures,
        successes,
        maximum_energy_drift,
    )


# ---------------------------------------------------------------------------
# IEVM/IPM probabilities and cross sections, equations (13)-(20)
# ---------------------------------------------------------------------------


def _ipm_exact_one_capture_and_transfer_ionization(
    pi: np.ndarray, pc: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """
    IPM probabilities for exactly one capture and for one capture plus one
    target ionization. All remaining target electrons undergo no removal.
    """
    n_impact = pi.shape[0]
    distribution = np.zeros((2, 2, n_impact), dtype=float)
    distribution[0, 0, :] = 1.0

    for shell_index, orbital in enumerate(WATER_ORBITALS):
        pn = np.clip(
            1.0 - pi[:, shell_index] - pc[:, shell_index],
            0.0,
            1.0,
        )
        for _ in range(orbital.active_electrons):
            updated = np.zeros_like(distribution)
            updated[0, 0] += distribution[0, 0] * pn
            updated[1, 0] += distribution[1, 0] * pn
            updated[0, 1] += distribution[0, 1] * pn
            updated[1, 1] += distribution[1, 1] * pn

            updated[1, 0] += distribution[0, 0] * pc[:, shell_index]
            updated[1, 1] += distribution[0, 1] * pc[:, shell_index]

            updated[0, 1] += distribution[0, 0] * pi[:, shell_index]
            updated[1, 1] += distribution[1, 0] * pi[:, shell_index]
            distribution = updated

    return distribution[1, 0], distribution[1, 1]


def many_electron_probabilities(
    pi: np.ndarray,
    pc: np.ndarray,
    pl: np.ndarray,
    charge_state: int,
) -> dict[str, np.ndarray]:
    if pi.shape != pc.shape or pi.ndim != 2:
        raise ValueError("pi and pc must have shape (n_impact, n_orbitals)")
    if pi.shape[1] != len(WATER_ORBITALS):
        raise ValueError("Unexpected number of water orbitals")
    if pl.shape != (pi.shape[0],):
        raise ValueError("pl must have shape (n_impact,)")

    pn = np.clip(1.0 - pi - pc, 0.0, 1.0)

    # Modified IEVM, equations (13) and (14), with NL=2 for every H2O
    # orbital and c=2 for pure double target ionization.
    si = np.zeros(pi.shape[0], dtype=float)
    di = np.zeros(pi.shape[0], dtype=float)
    for shell_index, orbital in enumerate(WATER_ORBITALS):
        nl = orbital.active_electrons
        si += nl * pi[:, shell_index] * pn[:, shell_index] ** (nl - 1)
        if nl >= 2:
            di += (
                0.5
                * nl
                * (nl - 1)
                * pi[:, shell_index] ** 2
                * pn[:, shell_index] ** (nl - 2)
            )

    sc, ti = _ipm_exact_one_capture_and_transfer_ionization(pi, pc)
    if charge_state == 0:
        sc.fill(0.0)
        ti.fill(0.0)

    projectile_orbital = CARBON_OUTER_ORBITAL.get(int(charge_state))
    if projectile_orbital is None:
        sl = np.zeros_like(pl)
    else:
        nl = projectile_orbital.active_electrons
        sl = nl * pl * np.clip(1.0 - pl, 0.0, 1.0) ** (nl - 1)

    li = si * sl
    if charge_state == 6:
        sl.fill(0.0)
        li.fill(0.0)

    channels = {
        "SI": si,
        "DI": di,
        "SC": sc,
        "TI": ti,
        "SL": sl,
        "LI": li,
    }
    for name, values in channels.items():
        if not np.all(np.isfinite(values)) or np.any(values < -1.0e-12):
            raise RuntimeError(f"Invalid {name} many-electron channel weight")
        # The modified IEVM sums shell-local removal terms (paper eqs. 13-14)
        # without the other-shell survival products present in the IPM. Its
        # channel weights can consequently exceed one at very small b. Do not
        # clip them: clipping would silently replace the published model by an
        # ad-hoc unitarization. SC and TI, evaluated with the IPM, remain
        # normalized probabilities.
        channels[name] = np.maximum(values, 0.0)

    channels["decrease"] = channels["SC"] + channels["TI"]
    channels["increase"] = channels["SL"] + channels["LI"]
    return channels


def integrate_impact_parameter(
    impact_au: np.ndarray, probability: np.ndarray
) -> float:
    sigma_bohr2 = 2.0 * math.pi * np.trapezoid(
        impact_au * probability, impact_au
    )
    return float(max(sigma_bohr2, 0.0) * BOHR2_CM2)


def build_cross_section_rows(
    energies: np.ndarray,
    charges: np.ndarray,
    impact_au: np.ndarray,
    pi: np.ndarray,
    pc: np.ndarray,
    pl: np.ndarray,
) -> tuple[np.ndarray, list[str]]:
    columns = [
        "E_keV_u",
        "q",
        "sigma_SC_cm2",
        "sigma_TI_cm2",
        "sigma_SL_cm2",
        "sigma_LI_cm2",
        "sigma_decrease_cm2",
        "sigma_increase_cm2",
        "sigma_SI_cm2",
        "sigma_DI_cm2",
    ]
    rows: list[list[float]] = []
    for energy_index, energy in enumerate(energies):
        for charge_index, charge in enumerate(charges):
            probabilities = many_electron_probabilities(
                pi[energy_index, charge_index],
                pc[energy_index, charge_index],
                pl[energy_index, charge_index],
                int(charge),
            )
            cross_sections = {
                name: integrate_impact_parameter(impact_au, values)
                for name, values in probabilities.items()
            }
            rows.append(
                [
                    float(energy),
                    float(charge),
                    cross_sections["SC"],
                    cross_sections["TI"],
                    cross_sections["SL"],
                    cross_sections["LI"],
                    cross_sections["decrease"],
                    cross_sections["increase"],
                    cross_sections["SI"],
                    cross_sections["DI"],
                ]
            )
    return np.asarray(rows, dtype=float), columns


