@lru_cache(maxsize=64)
def _microcanonical_radius_cdf(
    nuclear_charge: int,
    spectators: int,
    binding_eV_rounded: float,
    radial_grid_points: int,
) -> tuple[np.ndarray, np.ndarray]:
    core = CorePotential.from_zn(nuclear_charge, spectators)
    binding_ha = binding_eV_rounded / EV_PER_HARTREE

    def turning_point_function(radius: float) -> float:
        return potential_magnitude(core, radius) - binding_ha

    lower = 1.0e-12
    upper = max(2.0 * nuclear_charge / binding_ha, 1.0)
    while turning_point_function(upper) > 0.0:
        upper *= 2.0
        if upper > 1.0e8:
            raise RuntimeError("Could not bracket microcanonical turning point")
    rmax = brentq(turning_point_function, lower, upper, xtol=1.0e-13)

    positive_grid = np.geomspace(
        max(rmax * 1.0e-10, 1.0e-12),
        rmax * (1.0 - 1.0e-12),
        int(radial_grid_points) - 1,
    )
    radii = np.concatenate(([0.0], positive_grid, [rmax]))
    integrand = np.zeros_like(radii)
    for index in range(1, radii.size - 1):
        radius = float(radii[index])
        available = potential_magnitude(core, radius) - binding_ha
        integrand[index] = (
            radius
            * radius
            * math.sqrt(max(2.0 * available, 0.0))
        )
    cumulative = cumulative_trapezoid(integrand, radii, initial=0.0)
    if cumulative[-1] <= 0.0 or not np.isfinite(cumulative[-1]):
        raise RuntimeError("Invalid microcanonical radial distribution")
    cumulative /= cumulative[-1]
    return radii, cumulative


def _random_unit_vector(rng: np.random.Generator) -> np.ndarray:
    z = rng.uniform(-1.0, 1.0)
    phi = rng.uniform(0.0, 2.0 * math.pi)
    transverse = math.sqrt(max(1.0 - z * z, 0.0))
    return np.array(
        [transverse * math.cos(phi), transverse * math.sin(phi), z],
        dtype=float,
    )


def sample_bound_electron(
    core: CorePotential,
    core_mass_au: float,
    binding_eV: float,
    core_position: np.ndarray,
    core_velocity: np.ndarray,
    radial_grid_points: int,
    rng: np.random.Generator,
) -> tuple[np.ndarray, np.ndarray]:
    radii, cumulative = _microcanonical_radius_cdf(
        core.nuclear_charge,
        core.spectators,
        round(float(binding_eV), 10),
        int(radial_grid_points),
    )
    radius = float(np.interp(rng.random(), cumulative, radii))
    radius = max(radius, 1.0e-12)
    relative_position = radius * _random_unit_vector(rng)

    reduced_mass = (
        ELECTRON_MASS_AU
        * core_mass_au
        / (ELECTRON_MASS_AU + core_mass_au)
    )
    binding_ha = binding_eV / EV_PER_HARTREE
    kinetic_ha = potential_magnitude(core, radius) - binding_ha
    momentum = math.sqrt(max(2.0 * reduced_mass * kinetic_ha, 0.0))
    relative_velocity = (
        momentum / reduced_mass
    ) * _random_unit_vector(rng)

    return (
        np.asarray(core_position, dtype=float) + relative_position,
        np.asarray(core_velocity, dtype=float) + relative_velocity,
    )


