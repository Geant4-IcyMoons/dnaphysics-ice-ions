def _alpha_rudd_dcs_shape(incident_eV: float, transfer_eV: np.ndarray, shell: int) -> np.ndarray:
    """Geant4-DNA G4DNARuddIonisationModel alpha++ DCS shape for liquid water."""
    transfer = np.asarray(transfer_eV, dtype=float)
    binding = float(WATER_IONISATION_BINDINGS_EV[shell])
    secondary = transfer - binding
    out = np.zeros_like(transfer)
    valid = secondary >= 0.0
    if not np.any(valid):
        return out

    if shell == 4:
        A1, B1, C1, D1, E1 = 1.25, 0.5, 1.00, 1.00, 3.00
        A2, B2, C2, D2, alpha_const = 1.10, 1.30, 1.00, 0.00, 0.66
    else:
        A1, B1, C1, D1, E1 = 1.02, 82.0, 0.45, -0.80, 0.38
        A2, B2, C2, D2, alpha_const = 1.07, 11.6, 0.60, 0.04, 0.64

    gj = np.array([0.99, 1.11, 1.11, 0.52, 1.0], dtype=float)[shell]
    tau = (0.511 / 3728.0) * float(incident_eV)
    v2 = tau / binding
    if v2 <= 0.0:
        return out
    v = np.sqrt(v2)
    wc = 4.0 * v2 - 2.0 * v - (RYDBERG_EV / (4.0 * binding))
    s_factor = 4.0 * np.pi * BOHR_RADIUS_CM * BOHR_RADIUS_CM * 2.0 * (RYDBERG_EV / binding) ** 2
    w = secondary[valid] / binding
    l1 = (C1 * v**D1) / (1.0 + E1 * v ** (D1 + 4.0))
    l2 = C2 * v**D2
    h1 = (A1 * np.log1p(v2)) / (v2 + (B1 / v2))
    h2 = (A2 / v2) + (B2 / (v2 * v2))
    f1 = l1 + h1
    f2 = (l2 * h2) / (l2 + h2)
    denom = (1.0 + w) ** 3 * (1.0 + np.exp(alpha_const * (w - wc) / v))

    # For alpha++ Geant4 applies z_eff^2 = 4 to the Rudd water DCS.
    out[valid] = 4.0 * gj * (s_factor / binding) * ((f1 + w * f2) / denom)
    out[~np.isfinite(out)] = 0.0
    return out


def _alpha_rudd_eloss_xs(
    energy_grid: np.ndarray,
    rudd_energy: np.ndarray,
    rudd_components: np.ndarray,
    bindings: np.ndarray,
) -> np.ndarray:
    """Return energy-loss cross-section from Rudd DCS shape normalized to Geant4 tabulated sigma."""
    component_interp = [
        _interp_loglog(rudd_energy, rudd_components[:, i], energy_grid)
        for i in range(rudd_components.shape[1])
    ]
    eloss = np.zeros_like(energy_grid, dtype=float)
    for ie, incident in enumerate(np.asarray(energy_grid, dtype=float)):
        for shell, binding in enumerate(bindings):
            shell_sigma = float(component_interp[shell][ie])
            wmax = RUDD_ALPHA_WMAX_FACTOR * float(incident)
            if shell_sigma <= 0.0 or wmax <= 0.0:
                continue
            secondary = np.concatenate(([0.0], np.geomspace(1.0e-6, wmax, 280)))
            transfer = float(binding) + secondary
            shape = _alpha_rudd_dcs_shape(float(incident), transfer, shell)
            area = float(np.trapezoid(shape, transfer))
            if not np.isfinite(area) or area <= 0.0:
                continue
            mean_loss = float(np.trapezoid(transfer * shape, transfer) / area)
            if np.isfinite(mean_loss) and mean_loss > 0.0:
                eloss[ie] += shell_sigma * mean_loss
    return eloss


def _energy_loss_xs_with_cutoff(
    omega: np.ndarray,
    sigma: np.ndarray,
    cutoff_eV: float | None,
) -> float:
    order = np.argsort(omega)
    omega = np.asarray(omega, dtype=float)[order]
    sigma = np.asarray(sigma, dtype=float)[order]

    if cutoff_eV is None:
        return _simpson_nonuniform(omega, omega * sigma)

    cutoff = float(cutoff_eV)
    if cutoff <= float(np.min(omega)):
        return 0.0

    keep = omega <= cutoff
    x = omega[keep]
    y = sigma[keep]
    if cutoff < float(np.max(omega)) and np.any(omega < cutoff) and np.any(omega > cutoff):
        y_cut = float(np.interp(cutoff, omega, sigma))
        if x.size == 0 or not np.isclose(float(x[-1]), cutoff):
            x = np.append(x, cutoff)
            y = np.append(y, y_cut)
    if x.size < 2:
        return 0.0
    return _simpson_nonuniform(x, x * y)


def _dcs_moments_table(
    path: Path,
    projectile_mass_au: float,
    stopping_cutoff: str,
    drop_kshell: bool = False,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return incident energy, sigma_total, and energy-loss cross-section."""
    _ensure_exists(path)
    scale_cm2 = GEANT4_DNA_SCALE_CM2
    energies: list[float] = []
    sigma_xs: list[float] = []
    eloss_xs: list[float] = []

    current_e: float | None = None
    transfer_vals: list[float] = []
    sigma_vals: list[list[float]] = []
    n_channels: int | None = None

    def flush() -> None:
        if current_e is None or len(transfer_vals) < 2 or n_channels is None:
            return
        omega = np.asarray(transfer_vals, dtype=float)
        sigma = np.asarray(sigma_vals, dtype=float) * scale_cm2
        if drop_kshell and sigma.shape[0] >= 5:
            sigma = sigma[:-1, :]
        cutoff_eV = None
        if stopping_cutoff == "wmax_nonrel":
            cutoff_eV = min(float(current_e), _projectile_wmax_nonrel_eV(float(current_e), projectile_mass_au))
        sigma_sum = 0.0
        eloss_sum = 0.0
        for j in range(sigma.shape[0]):
            s = sigma[j]
            sigma_sum += _simpson_nonuniform(omega, s)
            eloss_sum += _energy_loss_xs_with_cutoff(omega, s, cutoff_eV)
        energies.append(float(current_e))
        sigma_xs.append(float(sigma_sum))
        eloss_xs.append(float(eloss_sum))

    with open(path, "r") as handle:
        for line in handle:
            if not line.strip():
                continue
            parts = line.split()
            if len(parts) < 3:
                continue
            incident_e = float(parts[0])
            transfer = float(parts[1])
            if n_channels is None:
                n_channels = len(parts) - 2
                sigma_vals = [[] for _ in range(n_channels)]
            if len(parts) < 2 + n_channels:
                continue
            if current_e is None:
                current_e = incident_e
            if incident_e != current_e:
                flush()
                current_e = incident_e
                transfer_vals = []
                sigma_vals = [[] for _ in range(n_channels)]
            transfer_vals.append(transfer)
            for j, value in enumerate(parts[2 : 2 + n_channels]):
                sigma_vals[j].append(float(value))
    flush()

    return (
        np.asarray(energies, dtype=float),
        np.asarray(sigma_xs, dtype=float),
        np.asarray(eloss_xs, dtype=float),
    )


def _to_dedx_ev_nm(eloss_xs: np.ndarray, n_cm3: float) -> np.ndarray:
    return (np.asarray(eloss_xs, dtype=float) * n_cm3) / CM_PER_NM


def _to_inverse_mfp_nm(sigma_xs: np.ndarray, n_cm3: float) -> np.ndarray:
    return (np.asarray(sigma_xs, dtype=float) * n_cm3) / CM_PER_NM


PROJECTILE_COMPONENT_KEYS = ("exc_eloss", "ion_eloss", "exc_sigma", "ion_sigma")


def _load_projectile_table_components(
    projectile_token: str,
    projectile_mass_au: float,
    ice_type: str,
    energy_grid: np.ndarray,
    stopping_cutoff: str,
    include_kshell: bool,
    table_set: str,
) -> dict:
    paths = _projectile_paths(projectile_token, ice_type, table_set)
    exc_energy, _, exc_eloss = _dcs_moments_table(paths["exc_dcs"], projectile_mass_au, stopping_cutoff)
    ion_energy, _, ion_eloss = _dcs_moments_table(
        paths["ion_dcs"],
        projectile_mass_au,
        stopping_cutoff,
        drop_kshell=not include_kshell,
    )
    exc_sigma_energy, exc_sigma = _load_total_sigma_table(paths["exc_total"])
    ion_sigma_energy, ion_sigma = _load_total_sigma_table(
        paths["ion_total"],
        drop_kshell=not include_kshell,
    )
    return {
        "table_set": table_set,
        "exc_eloss": _interp_loglog(exc_energy, exc_eloss, energy_grid),
        "ion_eloss": _interp_loglog(ion_energy, ion_eloss, energy_grid),
        "exc_sigma": _interp_loglog(exc_sigma_energy, exc_sigma, energy_grid),
        "ion_sigma": _interp_loglog(ion_sigma_energy, ion_sigma, energy_grid),
        "emin": max(
            float(np.min(exc_energy)),
            float(np.min(ion_energy)),
            float(np.min(exc_sigma_energy)),
            float(np.min(ion_sigma_energy)),
            float(np.min(energy_grid)),
        ),
        "emax": min(
            float(np.max(exc_energy)),
            float(np.max(ion_energy)),
            float(np.max(exc_sigma_energy)),
            float(np.max(ion_sigma_energy)),
            float(np.max(energy_grid)),
        ),
    }


def _difference_components(corrected: dict, bare: dict, label: str) -> tuple[dict, list[str]]:
    out = {
        "table_set": "barkas_difference",
        "emin": max(float(corrected["emin"]), float(bare["emin"])),
        "emax": min(float(corrected["emax"]), float(bare["emax"])),
    }
    warnings = []
    for key in PROJECTILE_COMPONENT_KEYS:
        diff = np.asarray(corrected[key], dtype=float) - np.asarray(bare[key], dtype=float)
        out[key] = diff
        nonfinite = int(np.count_nonzero(~np.isfinite(diff)))
        finite = diff[np.isfinite(diff)]
        negative = finite[finite < 0.0]
        if nonfinite:
            warnings.append(f"{label}: {key} corrected-minus-bare has {nonfinite} non-finite values.")
        if negative.size:
            warnings.append(
                f"{label}: {key} corrected-minus-bare has {negative.size} negative values "
                f"(min={float(np.min(negative)):.6g})."
            )
    return out, warnings


def _scale_components(components: dict, scale: np.ndarray | float) -> dict:
    out = {
        "table_set": components.get("table_set", ""),
        "emin": float(components["emin"]),
        "emax": float(components["emax"]),
    }
    for key in PROJECTILE_COMPONENT_KEYS:
        out[key] = np.asarray(components[key], dtype=float) * scale
    return out


def _add_components(left: dict, right: dict) -> dict:
    out = {
        "table_set": "combined",
        "emin": max(float(left["emin"]), float(right["emin"])),
        "emax": min(float(left["emax"]), float(right["emax"])),
    }
    for key in PROJECTILE_COMPONENT_KEYS:
        out[key] = np.asarray(left[key], dtype=float) + np.asarray(right[key], dtype=float)
    return out


def _append_bloch_label(label: str, include_bloch_stopping: bool) -> str:
    if not include_bloch_stopping:
        return label
    return f"{label} + Bloch"


def _components_to_series(
    components: dict,
    energy_grid: np.ndarray,
    ice_type: str,
    rho_ice: float | None,
    label: str,
    cross_section_tables: str,
    table_semantics: str,
    charge_scaling: str,
    barkas_difference_used: bool,
    warnings: list[str],
    projectile_charge: float,
    projectile_mass_au: float,
    charge_scale: np.ndarray,
    interaction_charge: np.ndarray,
    include_bloch_stopping: bool,
) -> dict:
    phase_density = ICE_DENSITY_BY_TYPE[ice_type]
    density = float(rho_ice) if rho_ice is not None else float(phase_density)
    n_cm3 = N_CM3_WATER * (density / WATER_DENSITY_G_CM3)

    exc_dedx = _to_dedx_ev_nm(components["exc_eloss"], n_cm3)
    ion_dedx = _to_dedx_ev_nm(components["ion_eloss"], n_cm3)
    dcs_total_dedx = exc_dedx + ion_dedx
    exc_imfp = _to_inverse_mfp_nm(components["exc_sigma"], n_cm3)
    ion_imfp = _to_inverse_mfp_nm(components["ion_sigma"], n_cm3)

    series_warnings = list(warnings)
    if include_bloch_stopping:
        bloch_eloss_xs = _bloch_eloss_xs_ev_cm2(energy_grid, projectile_mass_au, interaction_charge)
        bloch_dedx = _to_dedx_ev_nm(bloch_eloss_xs, n_cm3)
    else:
        bloch_eloss_xs = np.zeros_like(dcs_total_dedx)
        bloch_dedx = np.zeros_like(dcs_total_dedx)
    stopping_total_dedx = dcs_total_dedx + bloch_dedx

    with np.errstate(divide="ignore", invalid="ignore"):
        bloch_fraction = np.divide(
            bloch_dedx,
            dcs_total_dedx,
            out=np.full_like(bloch_dedx, np.nan, dtype=float),
            where=np.isfinite(dcs_total_dedx) & (dcs_total_dedx != 0.0),
        )
    if include_bloch_stopping:
        nonpositive = np.count_nonzero(np.isfinite(stopping_total_dedx) & (stopping_total_dedx <= 0.0))
        if nonpositive:
            series_warnings.append(
                "Bloch-corrected stopping power is non-positive at some energies; "
                "those values are invalid for log plotting."
            )
        too_large = np.count_nonzero(np.isfinite(bloch_fraction) & (np.abs(bloch_fraction) > 1.0))
        if too_large:
            series_warnings.append(
                "Bloch correction exceeds the DCS stopping magnitude; "
                "corrected-Bethe expansion may be outside its valid range."
            )

    if series_warnings:
        for warning in series_warnings:
            print(f"WARNING: {warning}")

    finite_bloch_fraction = bloch_fraction[np.isfinite(bloch_fraction)]
    finite_q = np.asarray(interaction_charge, dtype=float)
    finite_q = finite_q[np.isfinite(finite_q)]
    finite_bloch = bloch_dedx[np.isfinite(bloch_dedx)]

    return {
        "label": label,
        "ice_type": ice_type,
        "cross_section_tables": cross_section_tables,
        "table_semantics": table_semantics,
        "charge_scaling": charge_scaling,
        "barkas_difference_used": bool(barkas_difference_used),
        "warnings": series_warnings,
        "density_g_cm3": density,
        "charge_correction": charge_scaling,
        "projectile_charge_bare": float(projectile_charge),
        "zeff_scale_min": float(np.nanmin(charge_scale)),
        "zeff_scale_max": float(np.nanmax(charge_scale)),
        "include_bloch_stopping": bool(include_bloch_stopping),
        "bloch_charge_mode": "effective_charge" if "zeff" in str(charge_scaling) else "bare_charge",
        "bloch_interaction_charge_min": float(np.nanmin(finite_q)) if finite_q.size else None,
        "bloch_interaction_charge_max": float(np.nanmax(finite_q)) if finite_q.size else None,
        "bloch_min_ev_nm": float(np.nanmin(finite_bloch)) if finite_bloch.size else 0.0,
        "bloch_max_ev_nm": float(np.nanmax(finite_bloch)) if finite_bloch.size else 0.0,
        "bloch_min_fraction_of_dcs": (
            float(np.nanmin(finite_bloch_fraction)) if finite_bloch_fraction.size else None
        ),
        "bloch_max_fraction_of_dcs": (
            float(np.nanmax(finite_bloch_fraction)) if finite_bloch_fraction.size else None
        ),
        "emin": float(components["emin"]),
        "emax": float(components["emax"]),
        "dedx_exc": exc_dedx,
        "dedx_ion": ion_dedx,
        "dedx_dcs_total": dcs_total_dedx,
        "dedx_bloch": bloch_dedx,
        "bloch_eloss_xs_ev_cm2": bloch_eloss_xs,
        "dedx_stopping_total": stopping_total_dedx,
        "dedx_total": stopping_total_dedx,
        "imfp_exc": exc_imfp,
        "imfp_ion": ion_imfp,
        "imfp_total": exc_imfp + ion_imfp,
    }


def _build_series(
    projectile_token: str,
    projectile_label: str,
    projectile_mass_au: float,
    projectile_charge: float,
    ice_type: str,
    energy_grid: np.ndarray,
    rho_ice: float | None,
    stopping_cutoff: str,
    include_kshell: bool,
    barkas_zeff: bool,
    include_bloch_stopping: bool,
    cross_section_set: str = "bare",
) -> dict:
    bare = _load_projectile_table_components(
        projectile_token,
        projectile_mass_au,
        ice_type,
        energy_grid,
        stopping_cutoff,
        include_kshell,
        "bare",
    )
    corrected = None
    barkas = None
    difference_warnings: list[str] = []
    if cross_section_set == "barkas_dcs":
        corrected = _load_projectile_table_components(
            projectile_token,
            projectile_mass_au,
            ice_type,
            energy_grid,
            stopping_cutoff,
            include_kshell,
            "barkas_dcs",
        )
    if cross_section_set == "barkas_dcs" and barkas_zeff:
        if corrected is None:
            raise RuntimeError("Corrected table was not loaded for Barkas decomposition.")
        barkas, difference_warnings = _difference_components(
            corrected,
            bare,
            f"{projectile_label} {ice_type} ice",
        )

    one = np.ones_like(energy_grid, dtype=float)
    bare_charge = np.full_like(energy_grid, float(projectile_charge), dtype=float)
    effective_charge = _barkas_effective_charge(energy_grid, projectile_charge, projectile_mass_au)
    zeff_over_z_squared = _barkas_zeff_scale(energy_grid, projectile_charge, projectile_mass_au)
    zeff_over_z = np.sqrt(np.maximum(zeff_over_z_squared, 0.0))

    if cross_section_set == "bare":
        if barkas_zeff:
            components = _scale_components(bare, zeff_over_z_squared)
            label = f"{ice_type.capitalize()}: Born + z$_{{\\rm eff}}$"
            charge_scaling = "zeff_born_only"
            charge_scale = zeff_over_z_squared
            interaction_charge = effective_charge
        else:
            components = bare
            label = f"{ice_type.capitalize()}: Born"
            charge_scaling = "bare_charge"
            charge_scale = one
            interaction_charge = bare_charge
        return _components_to_series(
            components,
            energy_grid,
            ice_type,
            rho_ice,
            _append_bloch_label(label, include_bloch_stopping),
            "bare",
            "born_only",
            charge_scaling,
            False,
            [],
            projectile_charge,
            projectile_mass_au,
            charge_scale,
            interaction_charge,
            include_bloch_stopping,
        )

    if cross_section_set == "barkas_dcs":
        if corrected is None:
            raise RuntimeError("Corrected table was not loaded.")
        if barkas_zeff:
            if barkas is None:
                raise RuntimeError("Barkas difference was not available for Zeff decomposition.")
            born_scaled = _scale_components(bare, zeff_over_z_squared)
            barkas_scaled = _scale_components(barkas, zeff_over_z**3)
            components = _add_components(born_scaled, barkas_scaled)
            label = f"{ice_type.capitalize()}: Barkas + z$_{{\\rm eff}}$"
            charge_scaling = "zeff_decomposed_born_plus_barkas"
            charge_scale = zeff_over_z_squared
            barkas_difference_used = True
            warnings = difference_warnings
            interaction_charge = effective_charge
        else:
            components = corrected
            label = f"{ice_type.capitalize()}: Born + Barkas"
            charge_scaling = "bare_charge"
            charge_scale = one
            barkas_difference_used = False
            warnings = []
            interaction_charge = bare_charge
        return _components_to_series(
            components,
            energy_grid,
            ice_type,
            rho_ice,
            _append_bloch_label(label, include_bloch_stopping),
            "barkas_dcs",
            "born_plus_barkas_corrected",
            charge_scaling,
            barkas_difference_used,
            warnings,
            projectile_charge,
            projectile_mass_au,
            charge_scale,
            interaction_charge,
            include_bloch_stopping,
        )

    raise ValueError(f"Unsupported cross_section_set for series build: {cross_section_set!r}")


def _build_water_series(
    projectile_key: str,
    projectile_mass_au: float,
    energy_grid: np.ndarray,
    stopping_cutoff: str,
    include_kshell: bool,
) -> dict | None:
    if projectile_key == "alpha":
        path = _alpha_rudd_ionisation_path()
        if path is None:
            return None
        ion_energy, ion_components, bindings = _load_alpha_rudd_components(
            path,
            drop_kshell=not include_kshell,
        )
        ion_sigma = np.sum(ion_components, axis=1)
        ion_sigma_grid = _interp_loglog(ion_energy, ion_sigma, energy_grid)
        ion_eloss = _alpha_rudd_eloss_xs(energy_grid, ion_energy, ion_components, bindings)
        ion_dedx = _to_dedx_ev_nm(ion_eloss, N_CM3_WATER)
        ion_imfp = _to_inverse_mfp_nm(ion_sigma_grid, N_CM3_WATER)
        zeros = np.zeros_like(energy_grid)
        return {
            "label": "Geant4-DNA water (Rudd ion.)",
            "ice_type": "water",
            "source_model": "G4DNARuddIonisationModel alpha++ ionisation",
            "density_g_cm3": WATER_DENSITY_G_CM3,
            "emin": float(np.min(ion_energy)),
            "emax": float(np.max(ion_energy)),
            "dedx_exc": zeros,
            "dedx_ion": ion_dedx,
            "dedx_total": ion_dedx,
            "imfp_exc": zeros,
            "imfp_ion": ion_imfp,
            "imfp_total": ion_imfp,
        }

    paths = _water_born_paths(projectile_key)
    if paths is None:
        return None

    exc_energy, exc_components = _load_component_sigma_table(paths["exc_total"])
    exc_n = min(exc_components.shape[1], WATER_EXCITATION_ENERGIES_EV.size)
    exc_components = exc_components[:, :exc_n]
    exc_levels = WATER_EXCITATION_ENERGIES_EV[:exc_n]
    exc_sigma = np.sum(exc_components, axis=1)
    exc_eloss = np.sum(exc_components * exc_levels[None, :], axis=1)

    ion_energy, ion_sigma, ion_eloss = _dcs_moments_table(
        paths["ion_dcs"],
        projectile_mass_au,
        stopping_cutoff,
        drop_kshell=not include_kshell,
    )

    exc_dedx = _to_dedx_ev_nm(_interp_loglog(exc_energy, exc_eloss, energy_grid), N_CM3_WATER)
    ion_dedx = _to_dedx_ev_nm(_interp_loglog(ion_energy, ion_eloss, energy_grid), N_CM3_WATER)
    exc_imfp = _to_inverse_mfp_nm(_interp_loglog(exc_energy, exc_sigma, energy_grid), N_CM3_WATER)
    ion_imfp = _to_inverse_mfp_nm(_interp_loglog(ion_energy, ion_sigma, energy_grid), N_CM3_WATER)

    return {
        "label": "Geant4-DNA water",
        "ice_type": "water",
        "density_g_cm3": WATER_DENSITY_G_CM3,
        "emin": max(float(np.min(exc_energy)), float(np.min(ion_energy))),
        "emax": min(float(np.max(exc_energy)), float(np.max(ion_energy))),
        "dedx_exc": exc_dedx,
        "dedx_ion": ion_dedx,
        "dedx_total": exc_dedx + ion_dedx,
        "imfp_exc": exc_imfp,
        "imfp_ion": ion_imfp,
        "imfp_total": exc_imfp + ion_imfp,
    }


def _draw_manual_legend(ax, handles, labels) -> None:
    if not handles:
        return
    ncols = 2 if len(handles) > 4 else 1
    nrows = max(1, (len(handles) + ncols - 1) // ncols)
    fontsize = 18 if len(handles) > 4 else 22
    if nrows > 1:
        y_top, y_bottom = (0.55, 0.02) if ncols == 1 else (0.82, 0.18)
        y_values = np.linspace(y_top, y_bottom, nrows)
    else:
        y_values = np.array([0.5])
    col_width = 1.0 / ncols

    for idx, (handle, label) in enumerate(zip(handles, labels)):
        row = idx // ncols
        col = idx % ncols
        x0 = 0.40 if ncols == 1 else 0.04 + col * col_width
        y = float(y_values[row])
        line_x0 = x0
        line_x1 = x0 + 0.09
        text_x = x0 + 0.115
        ax.plot(
            [line_x0, line_x1],
            [y, y],
            transform=ax.transAxes,
            color=handle.get_color(),
            linestyle=handle.get_linestyle(),
            linewidth=handle.get_linewidth(),
            solid_capstyle="butt",
            clip_on=False,
        )
        ax.text(
            text_x,
            y,
            str(label),
            transform=ax.transAxes,
            ha="left",
            va="center",
            fontsize=fontsize,
            family=FONT_COURIER,
            clip_on=False,
        )


def _plot(
    energy_grid: np.ndarray,
    series: list[dict],
    units: str,
    projectile_key: str,
    projectile_axis_label: str,
    out_path: Path,
) -> None:
    expected_legend_count = len(series)
    if _load_icru_stopping_power(projectile_key) is not None:
        expected_legend_count += 1
    expected_legend_cols = 2 if expected_legend_count > 4 else 1
    expected_legend_rows = max(1, (expected_legend_count + expected_legend_cols - 1) // expected_legend_cols)
    legend_height_ratio = max(1.35, 0.62 * expected_legend_rows)
    fig_height = max(11.8, 10.4 + 0.68 * expected_legend_rows)

    fig = plt.figure(figsize=(10, fig_height))
    gs = fig.add_gridspec(
        4,
        1,
        height_ratios=[3.0, 0.9, 2.0, legend_height_ratio],
        hspace=0.15,
    )
    ax_sp = fig.add_subplot(gs[0, 0])
    ax_res = fig.add_subplot(gs[1, 0], sharex=ax_sp)
    ax_imfp = fig.add_subplot(gs[2, 0], sharex=ax_sp)
    ax_legend = fig.add_subplot(gs[3, 0])
    ax_legend.axis("off")
    ax_sp.tick_params(labelbottom=False)
    ax_res.tick_params(labelbottom=False)

    styles = {
        "amorphous": {"color": "SlateGray", "ls": "--"},
        "hexagonal": {"color": "0.55", "ls": "-"},
        "water": {"color": "#0072B2", "ls": "-."},
    }
    xmins = []
    xmaxs = []
    icru_curve = _load_icru_stopping_power(projectile_key)
    icru_energy = None
    icru_y = None
    icru_y_grid = None
    if icru_curve is not None:
        icru_energy, icru_mass_sp = icru_curve
        icru_y = _icru_mass_stopping_to_units(units, icru_mass_sp)
        icru_y_grid = _interp_loglog(icru_energy, icru_y, energy_grid)

    for item in series:
        item_energy = np.asarray(item.get("energy_eV", energy_grid), dtype=float)
        density = float(item["density_g_cm3"])
        y_sp, ylabel = _units_and_label(units, density, item["dedx_total"])
        y_imfp = item["imfp_total"]
        valid_sp = np.isfinite(item_energy) & (item_energy > 0.0) & np.isfinite(y_sp) & (y_sp > 0.0)
        valid_imfp = np.isfinite(item_energy) & (item_energy > 0.0) & np.isfinite(y_imfp) & (y_imfp > 0.0)
        emin = item.get("emin")
        emax = item.get("emax")
        if emin is not None:
            valid_sp &= item_energy >= float(emin)
            valid_imfp &= item_energy >= float(emin)
        if emax is not None:
            valid_sp &= item_energy <= float(emax)
            valid_imfp &= item_energy <= float(emax)
        valid_any = valid_sp | valid_imfp
        if np.any(valid_any):
            xmins.append(float(np.min(item_energy[valid_any])))
            xmaxs.append(float(np.max(item_energy[valid_any])))
        style = dict(styles.get(item["ice_type"], {"color": "0.5", "ls": "-"}))
        if item.get("charge_scaling") in {"zeff_born_only", "zeff_decomposed_born_plus_barkas"}:
            style["color"] = "#D55E00"
        if item.get("table_semantics") == "barkas_correction_only":
            style["color"] = "#CC79A7"
            style["ls"] = ":"
        ax_sp.loglog(
            item_energy[valid_sp],
            y_sp[valid_sp],
            color=style["color"],
            ls=style["ls"],
            linewidth=3,
            label=item["label"],
        )
        ax_imfp.loglog(
            item_energy[valid_imfp],
            y_imfp[valid_imfp],
            color=style["color"],
            ls=style["ls"],
            linewidth=3,
            label=item["label"],
        )
        if icru_y_grid is not None and item.get("ice_type") in {"amorphous", "hexagonal"}:
            icru_y_item = _interp_loglog(icru_energy, icru_y, item_energy)
            residual = (y_sp / icru_y_item) - 1.0
            valid_res = (
                valid_sp
                & np.isfinite(icru_y_item)
                & (icru_y_item > 0.0)
                & np.isfinite(residual)
            )
            if np.any(valid_res):
                ax_res.semilogx(
                    item_energy[valid_res],
                    residual[valid_res],
                    color=style["color"],
                    ls=style["ls"],
                    linewidth=2.4,
                )

    if icru_energy is not None and icru_y is not None:
        valid_icru = (
            np.isfinite(icru_energy)
            & np.isfinite(icru_y)
            & (icru_energy >= float(np.min(energy_grid)))
            & (icru_energy <= float(np.max(energy_grid)))
            & (icru_y > 0.0)
        )
        if np.any(valid_icru):
            ax_sp.loglog(
                icru_energy[valid_icru],
                icru_y[valid_icru],
                color="black",
                ls=":",
                linewidth=3,
                label=_icru_label(projectile_key),
                zorder=4,
            )

    ax_sp.set_ylabel(ylabel)
    ax_res.axhline(0.0, color="black", linewidth=1.0, alpha=0.7)
