def _simpson_nonuniform(x: np.ndarray, y: np.ndarray) -> float:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    mask = np.isfinite(x) & np.isfinite(y)
    x = x[mask]
    y = y[mask]
    if x.size < 2:
        return 0.0
    order = np.argsort(x)
    x = x[order]
    y = y[order]
    unique_x, inv = np.unique(x, return_inverse=True)
    if unique_x.size != x.size:
        y_sum = np.zeros_like(unique_x)
        counts = np.zeros_like(unique_x)
        for i, idx in enumerate(inv):
            y_sum[idx] += y[i]
            counts[idx] += 1.0
        x = unique_x
        y = y_sum / np.where(counts == 0.0, 1.0, counts)
    if x.size < 2:
        return 0.0
    if x.size == 2:
        return float(np.trapezoid(y, x))

    total = 0.0
    end = x.size if x.size % 2 == 1 else x.size - 1
    for i in range(0, end - 2, 2):
        x0, x1, x2 = x[i], x[i + 1], x[i + 2]
        y0, y1, y2 = y[i], y[i + 1], y[i + 2]
        h0 = x1 - x0
        h1 = x2 - x1
        if h0 <= 0.0 or h1 <= 0.0:
            continue
        w0 = 2.0 - h1 / h0
        w1 = ((h0 + h1) ** 2) / (h0 * h1)
        w2 = 2.0 - h0 / h1
        total += (h0 + h1) * (w0 * y0 + w1 * y1 + w2 * y2) / 6.0
    if x.size % 2 == 0:
        total += float(np.trapezoid(y[-2:], x[-2:]))
    return float(total)


def _interp_loglog(x: np.ndarray, y: np.ndarray, x_new: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    x_new = np.asarray(x_new, dtype=float)
    order = np.argsort(x)
    x = x[order]
    y = y[order]
    positive = (x > 0.0) & (y > 0.0)
    out = np.zeros_like(x_new)
    if np.count_nonzero(positive) < 2:
        return out
    xp = x[positive]
    yp = y[positive]
    mask = (x_new >= xp[0]) & (x_new <= xp[-1])
    out[mask] = 10.0 ** np.interp(
        np.log10(x_new[mask]),
        np.log10(xp),
        np.log10(yp),
    )
    out[~np.isfinite(out)] = 0.0
    return out


def _projectile_wmax_nonrel_eV(tau_eV: float, projectile_mass_au: float) -> float:
    return 4.0 * float(tau_eV) / float(projectile_mass_au)


def _projectile_beta(energy_eV: np.ndarray, projectile_mass_au: float) -> np.ndarray:
    energy = np.asarray(energy_eV, dtype=float)
    rest_eV = float(projectile_mass_au) * MC2_eV
    gamma = 1.0 + np.maximum(energy, 0.0) / rest_eV
    beta2 = 1.0 - 1.0 / np.square(gamma)
    return np.sqrt(np.maximum(beta2, 0.0))


def _barkas_effective_charge(energy_eV: np.ndarray, projectile_charge: float, projectile_mass_au: float) -> np.ndarray:
    """Barkas effective-charge formula for a projectile charge prefactor."""
    z = float(projectile_charge)
    energy = np.asarray(energy_eV, dtype=float)
    if z <= 0.0:
        return np.zeros_like(energy)
    beta = _projectile_beta(energy, projectile_mass_au)
    zeff = z * (1.0 - np.exp(-BARKAS_ZEFF_COEFF * beta * z ** (-2.0 / 3.0)))
    return np.clip(zeff, 0.0, z)


def _barkas_zeff_scale(energy_eV: np.ndarray, projectile_charge: float, projectile_mass_au: float) -> np.ndarray:
    z = float(projectile_charge)
    if z <= 0.0:
        return np.ones_like(np.asarray(energy_eV, dtype=float))
    zeff = _barkas_effective_charge(energy_eV, z, projectile_mass_au)
    return np.square(zeff / z)


def _bloch_log_correction(eta: np.ndarray, max_terms: int = 50000, tol: float = 1.0e-12) -> np.ndarray:
    """Bloch correction to the Bethe stopping logarithm."""
    eta = np.asarray(eta, dtype=float)
    eta2 = eta * eta
    total = np.zeros_like(eta, dtype=float)
    for n in range(1, max_terms + 1):
        nf = float(n)
        term = eta2 / (nf * (nf * nf + eta2))
        total += term
        if n > 1000 and np.nanmax(np.abs(term)) < tol:
            break
    return -total


def _bloch_eloss_xs_ev_cm2(
    energy_eV: np.ndarray,
    projectile_mass_au: float,
    interaction_charge: np.ndarray | float,
) -> np.ndarray:
    """Stopping-cross-section Bloch term; this is not a DCS/TCS correction."""
    beta = _projectile_beta(energy_eV, projectile_mass_au)
    beta = np.maximum(beta, 1.0e-300)
    q = np.asarray(interaction_charge, dtype=float)
    eta = q * FINE_STRUCTURE / beta
    delta_l = _bloch_log_correction(eta)
    return (
        4.0
        * np.pi
        * CLASSICAL_ELECTRON_RADIUS_CM**2
        * MC2_eV
        * TARGET_ELECTRONS_H2O
        * (q * q / (beta * beta))
        * delta_l
    )


