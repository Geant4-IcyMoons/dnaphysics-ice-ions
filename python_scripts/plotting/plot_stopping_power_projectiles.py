def _write_simulation_cache(path: Path, data: dict[str, np.ndarray], metadata: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {key: np.asarray(value, dtype=float) for key, value in data.items()}
    payload["metadata_json"] = np.asarray(json.dumps(metadata, indent=2))
    np.savez_compressed(path, **payload)


def _load_simulation_cache(
    path: Path,
    projectile_key: str,
    ice_type: str,
    emin_eV: float,
    emax_eV: float,
    nbins: int,
) -> tuple[dict[str, np.ndarray], dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(path)
    with np.load(path, allow_pickle=False) as cached:
        if "metadata_json" not in cached:
            raise RuntimeError(f"Simulation cache has no metadata_json field: {path}")
        metadata = json.loads(str(cached["metadata_json"].item()))
        expected = {
            "projectile": str(projectile_key),
            "ice_type": str(ice_type),
            "nbins": int(nbins),
            "simulation_reducer_version": SIMULATION_REDUCER_VERSION,
        }
        for key, value in expected.items():
            if metadata.get(key) != value:
                raise RuntimeError(
                    f"Simulation cache metadata mismatch for {key}: "
                    f"cache={metadata.get(key)!r}, requested={value!r}. "
                    f"Use rebuild_simulation_cache=True to overwrite {path}."
                )
        for key, value in (("emin_eV", float(emin_eV)), ("emax_eV", float(emax_eV))):
            cached_value = float(metadata.get(key, np.nan))
            if not np.isclose(cached_value, value, rtol=1e-12, atol=1e-9):
                raise RuntimeError(
                    f"Simulation cache metadata mismatch for {key}: "
                    f"cache={cached_value:.12g}, requested={value:.12g}. "
                    f"Use rebuild_simulation_cache=True to overwrite {path}."
                )
        data = {
            key: np.asarray(cached[key], dtype=float)
            for key in (
                "energy_eV",
                "path_length_nm",
                "n_inelastic",
                "stopping_power_eV_per_nm",
                "stopping_power_eV_per_A",
                "mass_stopping_power_MeV_cm2_g",
                "inverse_mfp_nm_inv",
                "imfp_nm",
                "sigma_excitation_cm2",
                "sigma_ionisation_cm2",
                "sigma_total_cm2",
            )
            if key in cached
        }
    required = {"energy_eV", "stopping_power_eV_per_nm", "inverse_mfp_nm_inv"}
    missing = sorted(required - set(data))
    if missing:
        raise RuntimeError(f"Simulation cache is missing required arrays {missing}: {path}")
    return data, metadata


def _required_table_sets(cross_section_mode: str, barkas_zeff: bool) -> tuple[str, ...]:
    if cross_section_mode == "bare":
        return ("bare",)
    if cross_section_mode == "both":
        return ("bare", "barkas_dcs")
    raise ValueError(f"Unsupported cross-section set: {cross_section_mode!r}")


def _series_requests(cross_section_mode: str, barkas_zeff: bool) -> list[tuple[str, bool]]:
    if cross_section_mode == "bare":
        if barkas_zeff:
            return [("bare", True)]
        return [("bare", False)]
    if cross_section_mode == "both":
        if barkas_zeff:
            return [("barkas_dcs", True)]
        return [("barkas_dcs", False)]
    raise ValueError(f"Unsupported cross-section set: {cross_section_mode!r}")


def _physics_filename_tag(
    cross_section_mode: str,
    barkas_zeff: bool,
    include_bloch_stopping: bool,
    include_kshell: bool,
    stopping_cutoff: str,
) -> str:
    table_tag = "born_barkas" if cross_section_mode == "both" else "born"
    charge_tag = "zeff" if barkas_zeff else "bareZ"
    bloch_tag = "_blochSP" if include_bloch_stopping else ""
    kshell_tag = "kshell" if include_kshell else "no_kshell"
    cutoff_tag = "" if stopping_cutoff == "none" else f"_{stopping_cutoff}"
    return f"{table_tag}_{charge_tag}{bloch_tag}_{kshell_tag}{cutoff_tag}"


def _print_water_icru_comparison(
    energy_grid: np.ndarray,
    water_series: dict | None,
    projectile_key: str,
    units: str,
) -> None:
    if water_series is None:
        return
    icru_curve = _load_icru_stopping_power(projectile_key)
    if icru_curve is None:
        return
    icru_energy, icru_mass_sp = icru_curve
    icru_y = _icru_mass_stopping_to_units(units, icru_mass_sp)
    target_e = 1.0e6
    if not (float(np.min(energy_grid)) <= target_e <= float(np.max(energy_grid))):
        target_e = float(np.sqrt(float(np.min(energy_grid)) * float(np.max(energy_grid))))
    water_y = _interp_loglog(energy_grid, water_series["dedx_total"], np.asarray([target_e]))[0]
    if units != "ev_nm":
        water_y = _units_and_label(units, WATER_DENSITY_G_CM3, np.asarray([water_y]))[0][0]
    icru_at_e = _interp_loglog(icru_energy, icru_y, np.asarray([target_e]))[0]
    if water_y > 0.0 and icru_at_e > 0.0:
        ratio = water_y / icru_at_e
        print(
            "Geant4-DNA water vs ICRU at "
            f"{target_e / 1.0e6:.6g} MeV: {water_y:.6g} vs {icru_at_e:.6g} "
            f"({ratio:.4g}x)"
        )


