def _config_csv(value: object) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, (list, tuple)):
        return ",".join(str(item) for item in value)
    return str(value)


def _config_bool(value: object, default: bool = False) -> bool:
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() not in {"0", "false", "no", "off"}


def _print_water_icru_comparison(
    energy_grid: np.ndarray,
    water_series: dict | None,
    projectile_key: str,
    units: str,
) -> None:
    if water_series is None:
        return
    icru_curve = _load_icru_stopping_power(projectile_key)
    if icru_curve is None:
        return
    icru_energy, icru_mass_sp = icru_curve
    icru_y = _icru_mass_stopping_to_units(units, icru_mass_sp)
    target_e = 1.0e6
    if not (float(np.min(energy_grid)) <= target_e <= float(np.max(energy_grid))):
        target_e = float(np.sqrt(float(np.min(energy_grid)) * float(np.max(energy_grid))))
    water_y = _interp_loglog(energy_grid, water_series["dedx_total"], np.asarray([target_e]))[0]
    if units != "ev_nm":
        water_y = _units_and_label(units, WATER_DENSITY_G_CM3, np.asarray([water_y]))[0][0]
    icru_at_e = _interp_loglog(icru_energy, icru_y, np.asarray([target_e]))[0]
    if water_y > 0.0 and icru_at_e > 0.0:
        ratio = water_y / icru_at_e
        print(
            "Geant4-DNA water vs ICRU at "
            f"{target_e / 1.0e6:.6g} MeV: {water_y:.6g} vs {icru_at_e:.6g} "
            f"({ratio:.4g}x)"
        )


def main(config: dict[str, object] | None = None) -> None:
    config = {} if config is None else config
    parser = argparse.ArgumentParser(
        description="Compute projectile stopping power and IMFP from generated DCS tables."
    )
    parser.add_argument(
        "--projectile",
        default=str(config.get("projectile", "proton")),
        help="proton, alpha, or carbon",
    )
    parser.add_argument(
        "--emin",
        type=float,
        default=float(config.get("emin", 1.0)),
        help="Minimum energy (eV)",
    )
    parser.add_argument(
        "--emax",
        type=float,
        default=float(config.get("emax", 1.0e8)),
        help="Maximum energy (eV)",
    )
    parser.add_argument(
        "--nbins",
        type=int,
        default=int(config.get("nbins", 500)),
        help="Number of log bins",
    )
    parser.add_argument(
        "--units",
        default=str(config.get("units", "ev_ang")),
        choices=("ev_ang", "ev_nm", "mev_cm", "mev_cm2_g"),
        help="Output units for stopping power.",
    )
    parser.add_argument(
        "--ice-types",
        default=_config_csv(config.get("ice_types", ("amorphous", "hexagonal"))),
        help="Comma-separated ice types to plot (amorphous,hexagonal).",
    )
    parser.add_argument(
        "--rho-ice",
        type=float,
        default=config.get("rho_ice", None),
        help="Override ice density (g/cm^3).",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=config.get("out", None),
        help="Output plot path.",
    )
    parser.add_argument(
        "--stopping-cutoff",
        default=str(config.get("stopping_cutoff", "none")),
        choices=("none", "wmax_nonrel"),
        help=(
            "Optional stopping-power-only energy-transfer cutoff. "
            "Use wmax_nonrel to test the 2009 heavy-projectile convention; "
            "IMFP/total cross sections are unchanged."
        ),
    )
    parser.add_argument(
        "--include-water",
        action=argparse.BooleanOptionalAction,
        default=_config_bool(config.get("include_water", True), True),
        help="Overlay Geant4-DNA water stopping/IMFP where native water tables are available.",
    )
    args = parser.parse_args()

    if args.emin <= 0.0 or args.emax <= 0.0 or args.emin >= args.emax:
        raise ValueError("Invalid energy range.")
    projectile_key, projectile = _projectile_config(args.projectile)
    projectile_token = str(projectile["file_token"])
    projectile_label = str(projectile["label"])
    projectile_mass_au = float(projectile["mass_au"])
    projectile_axis_label = PROJECTILE_AXIS_LABELS.get(projectile_key, projectile_key.capitalize())
    ice_types = [v.strip().lower() for v in args.ice_types.split(",") if v.strip()]
    ice_types = [v for v in ice_types if v in ICE_DENSITY_BY_TYPE]
    if not ice_types:
        raise ValueError("No valid ice types specified.")

    coverage = {
        ice_type: _plot_energy_range(projectile_token, ice_type)
        for ice_type in ice_types
    }
    domain_emin = max(bounds[0] for bounds in coverage.values())
    domain_emax = min(bounds[1] for bounds in coverage.values())
    plot_emin = max(float(args.emin), domain_emin)
    plot_emax = min(float(args.emax), domain_emax)
    if plot_emin >= plot_emax:
        raise ValueError(
            "Requested energy range does not overlap the generated projectile "
            f"cross-section domain ({domain_emin:.6g} to {domain_emax:.6g} eV)."
        )
    if plot_emin != args.emin or plot_emax != args.emax:
        print(
            "Using projectile generated-energy domain "
            f"{plot_emin:.6g} to {plot_emax:.6g} eV "
            "(from the generator T_list cache when available)."
        )

    energy = np.logspace(np.log10(plot_emin), np.log10(plot_emax), args.nbins)
    series = [
        _build_series(
            projectile_token,
            projectile_label,
            projectile_mass_au,
            ice_type,
            energy,
            args.rho_ice,
            args.stopping_cutoff,
        )
        for ice_type in ice_types
    ]
    water_series = None
    if args.include_water:
        water_series = _build_water_series(
            projectile_key,
            projectile_mass_au,
            energy,
            args.stopping_cutoff,
        )
        if water_series is not None:
            series.append(water_series)
        else:
            print(f"No Geant4-DNA water Born table overlay is available for {projectile_key}.")

    out_path = args.out
    if out_path is None:
        ice_suffix = "_".join(ice_types)
        out_path = OUTPUT_DIR / f"stopping_power_imfp_{projectile_key}_{ice_suffix}_ice.png"

    _plot(
        energy_grid=energy,
        series=series,
        units=args.units,
        projectile_key=projectile_key,
        projectile_axis_label=projectile_axis_label,
        out_path=out_path,
    )
    _print_water_icru_comparison(energy, water_series, projectile_key, args.units)


if __name__ == "__main__":
    RUN_CONFIG = {
        "projectile": "proton",
        "ice_types": ("amorphous", "hexagonal"),
        "stopping_cutoff": "wmax_nonrel",
        "include_water": True,
    }

    main(RUN_CONFIG)
